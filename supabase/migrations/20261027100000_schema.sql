-- Trigger genérico. Se puede desactivar en la sesión con: set app.skip_audit = 'on' (seeds).
create or replace function public.fn_audit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old jsonb;
  v_new jsonb;
  v_row jsonb;
  v_det jsonb;
  v_reg text;
begin
  if coalesce(current_setting('app.skip_audit', true), '') = 'on' then
    return null;
  end if;
  if tg_op <> 'INSERT' then v_old := to_jsonb(old); end if;
  if tg_op <> 'DELETE' then v_new := to_jsonb(new); end if;
  v_row := coalesce(v_new, v_old);
  if tg_table_name = 'ordenes_compra' then
    v_reg := (v_row ->> 'obra_id') || '/' || (v_row ->> 'numero');
  else
    v_reg := v_row ->> 'id';
  end if;
  if tg_op = 'UPDATE' then
    select jsonb_object_agg(n.key, jsonb_build_object('old', v_old -> n.key, 'new', n.value))
      into v_det
      from jsonb_each(v_new) n
     where n.value is distinct from (v_old -> n.key)
       and n.key not in ('updated_at', 'updated_by');
    if v_det is null then
      return null;
    end if;
  else
    v_det := v_row;
  end if;
  insert into public.audit_log (user_id, tabla, registro, accion, detalle)
  values (auth.uid(), tg_table_name, v_reg, tg_op, v_det);
  return null;
end;
$$;

create trigger audit_ordenes_compra after insert or update or delete on public.ordenes_compra
  for each row execute function public.fn_audit();
create trigger audit_oc_items after insert or update or delete on public.oc_items
  for each row execute function public.fn_audit();
create trigger audit_comprobantes after insert or update or delete on public.comprobantes
  for each row execute function public.fn_audit();
create trigger audit_pagos after insert or update or delete on public.pagos
  for each row execute function public.fn_audit();
create trigger audit_pago_aplicaciones after insert or update or delete on public.pago_aplicaciones
  for each row execute function public.fn_audit();
create trigger audit_asientos after insert or update or delete on public.asientos
