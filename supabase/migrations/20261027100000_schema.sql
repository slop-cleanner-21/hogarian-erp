-- ERP MVP: esquema base (tablas, enums, restricciones, auditoría, RLS, storage).
-- Modelo derivado de "CONTROL DE COSTOS V2.2.xlsm". Ver docs/modelo-datos.md.

-- ============================================================ enums
create type public.rubro as enum
  ('MATERIAL', 'MANO OBRA', 'SUBCONTRATO', 'LOCACION', 'PROYECTO', 'FINALIZACION', 'OTRO');
-- Excel L!B12:B16: R.HONORARIOS->RXH, RECIBO SIMPLE->RECIBO_SIMPLE
create type public.tipo_comprobante as enum ('FACTURA', 'RXH', 'BOLETA', 'RECIBO_SIMPLE', 'OTRO');
create type public.estado_oc as enum
  ('BORRADOR', 'EMITIDA', 'PRECIOS_CONFIRMADOS', 'FACTURADA', 'PAGADA', 'ANULADA');
create type public.tipo_orden as enum ('OC', 'OS');
create type public.rol as enum ('LOGISTICA', 'CONTABILIDAD', 'TESORERIA', 'ADMIN');

-- ============================================================ usuarios
create table public.perfiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  nombre  text not null,
  rol     public.rol not null default 'LOGISTICA'
);

-- ============================================================ maestros
create table public.empresas (
  id     bigint generated by default as identity primary key,
  nombre text not null unique,
  ruc    text unique check (ruc ~ '^\d{11}$')
);

create table public.obras (
  id         bigint generated by default as identity primary key,
  nombre     text not null unique,
  empresa_id bigint not null references public.empresas (id),
  estado     text not null default 'EN_EJECUCION'
);
create index obras_empresa_idx on public.obras (empresa_id);

-- L0, L1A..L5B, ACB 1-5, IE 1-5, IS 1-5 (grupo = prefijo)
create table public.etapas (
  codigo text primary key,
  grupo  text not null,
  orden  int not null default 0
);

-- REGULAR, ADIC 1..ADIC 25
create table public.requerimientos (
  codigo text primary key,
  orden  int not null default 0
);

create table public.cuentas_contables (
  codigo       text primary key check (codigo ~ '^\d{2,8}$'),
  denominacion text not null,
  tipo         text not null check (tipo in ('ACTIVO', 'PASIVO', 'PATRIMONIO', 'GASTO', 'INGRESO'))
);

-- Tipo de material (clasificación para filtrar partidas en la emisión de órdenes)
create table public.tipos_material (
  codigo text primary key,
  orden  int not null default 0
);
insert into public.tipos_material (codigo, orden) values
  ('ACERO', 1), ('CEMENTO', 2), ('AGREGADOS', 3), ('SERVICIOS SANITARIOS', 4), ('SERVICIOS ELECTRICOS', 5);

create table public.items (
  id              bigint generated by default as identity primary key,
  numero          int,
  descripcion     text not null unique,
  unidad          text,
  rubro           public.rubro not null,
  tolerancia_pct  numeric(6,4) not null default 0 check (tolerancia_pct >= 0),
  cuenta_contable text references public.cuentas_contables (codigo),
  tipo_material   text references public.tipos_material (codigo) on update cascade
);
create index items_cuenta_idx on public.items (cuenta_contable);
create index items_tipo_material_idx on public.items (tipo_material);

create table public.proveedores (
  id                   bigint generated by default as identity primary key,
  ruc_o_cod            text not null unique,
  razon_social         text not null,
  comprobante_habitual public.tipo_comprobante,
  comprobante_excel    text,   -- valor original de PROVEED.D (trazabilidad del mapeo)
  banco                text,
  cuenta_bancaria      text
);

-- ============================================================ presupuesto
create sequence public.partidas_codigo_seq;

create table public.partidas (
  id            bigint generated by default as identity primary key,
  codigo        text not null unique default ('G' || nextval('public.partidas_codigo_seq')),
  obra_id       bigint not null references public.obras (id),
  etapa         text not null references public.etapas (codigo) on update cascade,
  requerimiento text not null default 'REGULAR' references public.requerimientos (codigo) on update cascade,
  item_id       bigint not null references public.items (id),
  cantidad      numeric(14,4) not null default 0 check (cantidad >= 0),
  pu            numeric(12,4) check (pu >= 0),  -- null = sin precio presupuestado (sin control de precio)
  unique (id, obra_id)
);
alter sequence public.partidas_codigo_seq owned by public.partidas.codigo;
create index partidas_obra_idx on public.partidas (obra_id);
create index partidas_item_idx on public.partidas (item_id);

-- ============================================================ compras
create table public.ordenes_compra (
  obra_id          bigint not null references public.obras (id),
  numero           text not null check (btrim(numero) <> ''),
  tipo             public.tipo_orden not null default 'OC',
  proveedor_id     bigint not null references public.proveedores (id),
  fecha            date not null default current_date,
  estado           public.estado_oc not null default 'BORRADOR',
  token_cotizacion uuid not null unique default gen_random_uuid(),
  motivo_anulacion text,
  created_by       uuid default auth.uid(),
  updated_by       uuid,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  primary key (obra_id, numero),
  check (estado <> 'ANULADA' or motivo_anulacion is not null)
);
create index ordenes_proveedor_idx on public.ordenes_compra (proveedor_id);
create index ordenes_estado_idx on public.ordenes_compra (estado);

create table public.comprobantes (
  id            bigint generated by default as identity primary key,
  empresa_id    bigint not null references public.empresas (id),
  proveedor_id  bigint not null references public.proveedores (id),
  tipo          public.tipo_comprobante not null,
  serie         text not null,
  numero        text not null,
  fecha_emision date not null,
  total         numeric(14,2) not null check (total >= 0),
  base          numeric(14,2) not null,   -- calculado por trigger si viene null
  igv           numeric(14,2) not null,
  retencion     numeric(14,2) not null default 0 check (retencion >= 0 and retencion <= total),
  archivo_path  text,
  created_by    uuid default auth.uid(),
  created_at    timestamptz not null default now(),
  unique (proveedor_id, tipo, serie, numero)
);
create index comprobantes_empresa_idx on public.comprobantes (empresa_id, fecha_emision);

create table public.oc_items (
  id             bigint generated by default as identity primary key,
  obra_id        bigint not null,
  numero_oc      text not null,
  partida_id     bigint not null,
  cantidad       numeric(14,4) not null check (cantidad > 0),
  pu_cotizado    numeric(12,4) check (pu_cotizado >= 0),
  pu_aprobado    numeric(12,4) check (pu_aprobado >= 0),  -- Excel X: sobreprecio aprobado
  aprobado_por   uuid,
  comprobante_id bigint references public.comprobantes (id) on delete set null,
  created_at     timestamptz not null default now(),
  foreign key (obra_id, numero_oc) references public.ordenes_compra (obra_id, numero)
    on update cascade on delete cascade,
  -- garantiza que la partida pertenece a la obra de la orden
  foreign key (partida_id, obra_id) references public.partidas (id, obra_id)
);
create index oc_items_orden_idx on public.oc_items (obra_id, numero_oc);
create index oc_items_partida_idx on public.oc_items (partida_id);
create index oc_items_comprobante_idx on public.oc_items (comprobante_id);

