-- ============================================================ triggers de apoyo
create or replace function public.fn_set_updated()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end;
$$;

create trigger ordenes_compra_updated before update on public.ordenes_compra
  for each row execute function public.fn_set_updated();

-- base/igv: FACTURA -> base = round(total/1.18, 2), igv = total - base; otros -> base = total, igv = 0
create or replace function public.fn_comprobante_montos()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' and (new.total is distinct from old.total or new.tipo is distinct from old.tipo)
     and new.base is not distinct from old.base and new.igv is not distinct from old.igv then
    new.base := null;
    new.igv := null;
  end if;
  if new.base is null then
    new.base := case when new.tipo = 'FACTURA' then round(new.total / 1.18, 2) else new.total end;
  end if;
  if new.igv is null then
    new.igv := new.total - new.base;
  end if;
  return new;
end;
$$;

create trigger comprobantes_montos before insert or update on public.comprobantes
  for each row execute function public.fn_comprobante_montos();

-- ============================================================ RLS (MVP: authenticated todo, anon nada)
do $$
declare
  t text;
begin
  foreach t in array array['perfiles', 'empresas', 'obras', 'etapas', 'requerimientos', 'cuentas_contables', 'tipos_material',
                           'items', 'proveedores', 'partidas', 'ordenes_compra', 'oc_items', 'comprobantes',
                           'pagos', 'pago_aplicaciones', 'asientos', 'asiento_lineas']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy %I on public.%I for all to authenticated using (true) with check (true)',
                   t || '_authenticated_all', t);
  end loop;
end;
$$;

-- audit_log: solo lectura (lo escribe fn_audit como security definer)
alter table public.audit_log enable row level security;
create policy audit_log_authenticated_select on public.audit_log for select to authenticated using (true);

revoke all on all tables in schema public from anon;
revoke all on all sequences in schema public from anon;
grant select, insert, update, delete on all tables in schema public to authenticated, service_role;
revoke insert, update, delete on public.audit_log from authenticated;
grant usage, select on all sequences in schema public to authenticated, service_role;

