-- Presupuesto efectivo: lo presupuestado + lo adelantado de etapas posteriores - lo prestado a etapas anteriores.
create or replace view public.v_presupuesto_efectivo with (security_invoker = true) as
select p.id as partida_id, p.obra_id, p.item_id, p.etapa, p.cantidad,
       coalesce(r.recibido, 0) as recibido,
       coalesce(d.dado, 0) as dado,
       p.cantidad + coalesce(r.recibido, 0) - coalesce(d.dado, 0) as efectivo
  from public.partidas p
  left join lateral (select sum(a.cantidad) as recibido from public.adelantos a join public.requerimientos_obra q on q.id = a.requerimiento_id
                      where a.partida_destino_id = p.id and q.estado = 'VIGENTE') r on true
  left join lateral (select sum(a.cantidad) as dado from public.adelantos a join public.requerimientos_obra q on q.id = a.requerimiento_id
                      where a.partida_origen_id = p.id and q.estado = 'VIGENTE') d on true;
grant select on public.v_presupuesto_efectivo to authenticated;

create or replace function public.fn_presupuesto_efectivo(p_partida_id bigint)
returns numeric
language sql
stable
security definer
set search_path = public
as $$
  select efectivo from v_presupuesto_efectivo where partida_id = p_partida_id;
$$;

create or replace function public.fn_requerido_partida(p_partida_id bigint)
returns numeric
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(sum(ri.cantidad), 0) from requerimientos_obra_items ri join requerimientos_obra q on q.id = ri.requerimiento_id
   where ri.partida_id = p_partida_id and q.estado = 'VIGENTE';
$$;

-- Lo comprometido en órdenes (si la entrega se cerró incompleta, solo lo entregado).
create or replace function public.fn_comprometido_partida(p_partida_id bigint)
returns numeric
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(sum(case when o.entrega_cerrada_at is null then l.cantidad
                           else coalesce((select sum(en.cantidad) from entregas en where en.oc_item_id = l.id), 0) end), 0)
    from oc_items l join ordenes_compra o on o.obra_id = l.obra_id and o.numero = l.numero_oc
   where l.partida_id = p_partida_id and o.estado not in ('ANULADA', 'BORRADOR');
$$;

create or replace view public.v_partidas with (security_invoker = true) as
SELECT p.id,
    p.codigo,
    p.obra_id,
    ob.nombre AS obra,
    ob.empresa_id,
    p.etapa,
    p.requerimiento,
    p.item_id,
    i.descripcion,
    i.unidad,
    i.rubro,
    p.cantidad,
    p.pu,
    round((p.cantidad * p.pu), 2) AS parcial,
    round(fn_pu_max(p.pu, i.tolerancia_pct), 4) AS pu_max,
    COALESCE(x.cant, (0)::numeric) AS cant_comprometida,
    COALESCE(x.monto, (0)::numeric) AS monto_ejecutado,
    (ef.efectivo - COALESCE(x.cant, (0)::numeric)) AS saldo_cant,
    (COALESCE(round((ef.efectivo * p.pu), 2), (0)::numeric) - COALESCE(x.monto, (0)::numeric)) AS saldo_monto,
        CASE
            WHEN (ef.efectivo > (0)::numeric) THEN round((COALESCE(x.cant, (0)::numeric) / ef.efectivo), 4)
            ELSE NULL::numeric
        END AS avance,
    i.tipo_material,
    ef.efectivo AS cantidad_efectiva,
    ef.recibido AS adelanto_recibido,
    ef.dado AS adelanto_dado
   FROM ((((partidas p
     JOIN v_presupuesto_efectivo ef ON ((ef.partida_id = p.id)))
     JOIN obras ob ON ((ob.id = p.obra_id)))
     JOIN items i ON ((i.id = p.item_id)))
     LEFT JOIN LATERAL ( SELECT sum(
                CASE
                    WHEN (oc.entrega_cerrada_at IS NULL) THEN c.cantidad
                    ELSE COALESCE(( SELECT sum(en.cantidad) AS sum
                       FROM entregas en
                      WHERE (en.oc_item_id = c.id)), (0)::numeric)
                END) AS cant,
            sum(
                CASE
                    WHEN (oc.entrega_cerrada_at IS NULL) THEN COALESCE(c.parcial, (0)::numeric)
                    ELSE round((COALESCE(( SELECT sum(en.cantidad) AS sum
                       FROM entregas en
                      WHERE (en.oc_item_id = c.id)), (0)::numeric) * COALESCE(c.pu_efectivo, (0)::numeric)), 2)
                END) AS monto
           FROM (v_oc_items_calc c
             JOIN ordenes_compra oc ON (((oc.obra_id = c.obra_id) AND (oc.numero = c.numero_oc))))
          WHERE ((c.partida_id = p.id) AND (c.estado <> ALL (ARRAY['ANULADA'::estado_oc, 'BORRADOR'::estado_oc])))) x ON (true))
  WHERE (p.dada_de_baja_at IS NULL);

CREATE OR REPLACE FUNCTION public.crear_orden(p_obra_id bigint, p_numero text, p_proveedor_id bigint, p_tipo tipo_orden, p_items jsonb)
 RETURNS text
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_numero text;
  v_p record;
  r record;
  v_comp numeric;
begin
  if not exists (select 1 from obras where id = p_obra_id) then
    raise exception 'La obra % no existe', p_obra_id;
  end if;
  if not exists (select 1 from proveedores where id = p_proveedor_id) then
    raise exception 'El proveedor % no existe', p_proveedor_id;
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'La orden debe tener al menos un ítem';
  end if;
  if exists (select 1 from jsonb_to_recordset(p_items) x(partida_id bigint, cantidad numeric)
              where x.partida_id is null or x.cantidad is null or x.cantidad <= 0) then
    raise exception 'Cada ítem requiere partida_id y una cantidad mayor que cero';
  end if;

  v_numero := nullif(btrim(p_numero), '');
  if v_numero is null then
    v_numero := siguiente_numero_oc(p_obra_id);
  end if;
  if exists (select 1 from ordenes_compra where obra_id = p_obra_id and numero = v_numero) then
    raise exception 'Ya existe la orden % en esta obra', v_numero;
  end if;

  -- valida saldo de cada partida (bloqueadas en orden de id para evitar deadlocks)
  for r in
    select x.partida_id, sum(x.cantidad) as cantidad
      from jsonb_to_recordset(p_items) x(partida_id bigint, cantidad numeric)
     group by x.partida_id
     order by x.partida_id
  loop
    select p.obra_id, fn_presupuesto_efectivo(p.id) as cantidad, p.codigo into v_p
      from partidas p where p.id = r.partida_id for update;
    if not found then
      raise exception 'La partida % no existe', r.partida_id;
    end if;
    if v_p.obra_id <> p_obra_id then
      raise exception 'La partida % no pertenece a la obra de la orden', v_p.codigo;
    end if;
    -- Si la entrega de una orden se cerró incompleta, lo que no llegó vuelve al saldo.
    select coalesce(sum(case when o.entrega_cerrada_at is null then l.cantidad
                             else coalesce((select sum(en.cantidad) from entregas en where en.oc_item_id = l.id), 0) end), 0) into v_comp
      from oc_items l
      join ordenes_compra o on o.obra_id = l.obra_id and o.numero = l.numero_oc
     where l.partida_id = r.partida_id
       and o.estado not in ('ANULADA', 'BORRADOR');
    if r.cantidad > v_p.cantidad - v_comp then
      raise exception 'La cantidad solicitada (%) de la partida % excede su saldo disponible (%)',
        trim_scale(r.cantidad), v_p.codigo, trim_scale(v_p.cantidad - v_comp);
    end if;
  end loop;

  insert into ordenes_compra (obra_id, numero, tipo, proveedor_id, fecha, estado)
  values (p_obra_id, v_numero, coalesce(p_tipo, 'OC'), p_proveedor_id, current_date, 'EMITIDA');

  -- En la OS el precio de partida es el del presupuesto: Logística solo confirma lo que no cambie.
  insert into oc_items (obra_id, numero_oc, partida_id, cantidad, pu_cotizado)
  select p_obra_id, v_numero, x.partida_id, x.cantidad, case when coalesce(p_tipo, 'OC') = 'OS' then p.pu end
    from rows from (jsonb_to_recordset(p_items) as (partida_id bigint, cantidad numeric))
         with ordinality as x(partida_id, cantidad, n)
    join partidas p on p.id = x.partida_id
   order by x.n;

  return v_numero;
exception
  when unique_violation then
    raise exception 'Ya existe la orden % en esta obra', v_numero;
end;
$function$;

CREATE OR REPLACE FUNCTION public.guardar_partidas(p_obra_id bigint, p_partidas jsonb, p_eliminar bigint[])
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_rol text := rol_actual();
  v_estado text;
  r record;
  v_comprado numeric;
  v_n integer := 0;
begin
  select presupuesto_estado into v_estado from obras where id = p_obra_id for update;
  if not found then
    raise exception 'La obra no existe';
  end if;
  if v_rol not in ('GERENCIA', 'ADMIN') then
    raise exception 'Solo Gerencia carga y modifica el presupuesto';
  end if;

  -- Bajas: solo partidas sin órdenes.
  if p_eliminar is not null and cardinality(p_eliminar) > 0 then
    if exists (select 1 from oc_items where partida_id = any (p_eliminar)) then
      raise exception 'No se puede quitar una partida que ya tiene órdenes';
    end if;
    if exists (select 1 from requerimientos_obra_items where partida_id = any (p_eliminar))
       or exists (select 1 from adelantos where partida_origen_id = any (p_eliminar) or partida_destino_id = any (p_eliminar)) then
      raise exception 'No se puede quitar una partida que ya tiene requerimientos o adelantos';
    end if;
    delete from partidas where obra_id = p_obra_id and id = any (p_eliminar);
    get diagnostics v_n = row_count;
  end if;

  for r in select * from jsonb_to_recordset(coalesce(p_partidas, '[]'::jsonb))
                        x(id bigint, etapa text, requerimiento text, item_id bigint, cantidad numeric, pu numeric) loop
    if r.etapa is null or r.item_id is null or r.cantidad is null or r.cantidad < 0 or (r.pu is not null and r.pu < 0) then
      raise exception 'Cada partida necesita etapa, ítem, cantidad y P.U. válidos';
    end if;
    if r.id is null then
      insert into partidas (obra_id, etapa, requerimiento, item_id, cantidad, pu)
      values (p_obra_id, r.etapa, coalesce(r.requerimiento, 'REGULAR'), r.item_id, r.cantidad, r.pu);
    else
      select coalesce(sum(l.cantidad), 0) into v_comprado
        from v_oc_items_calc l where l.partida_id = r.id and l.estado <> 'ANULADA';
      -- Con adelantos, lo que cuenta es el presupuesto efectivo (cantidad + recibido - dado).
      if r.cantidad + fn_presupuesto_efectivo(r.id) - (select cantidad from partidas where id = r.id) < v_comprado - 0.0001 then
        raise exception 'La cantidad de una partida no puede quedar debajo de lo ya comprado (%), contando sus adelantos', v_comprado;
      end if;
      update partidas set etapa = r.etapa, requerimiento = coalesce(r.requerimiento, 'REGULAR'), item_id = r.item_id,
                          cantidad = r.cantidad, pu = r.pu
       where id = r.id and obra_id = p_obra_id;
    end if;
    v_n := v_n + 1;
  end loop;
  return v_n;
end;
$function$;

CREATE OR REPLACE FUNCTION public.resolver_solicitud(p_id bigint, p_aprobar boolean, p_respuesta text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  s solicitudes%rowtype;
  r record;
  v_titulo text;
begin
  if rol_actual() not in ('GERENCIA', 'ADMIN') then
    raise exception 'Solo Gerencia resuelve solicitudes';
  end if;
  select * into s from solicitudes where id = p_id for update;
  if not found or s.estado <> 'PENDIENTE' then
    raise exception 'La solicitud ya fue resuelta';
  end if;

  if p_aprobar then
    if s.tipo = 'ADICIONAL' then
      insert into partidas (obra_id, etapa, requerimiento, item_id, cantidad, pu)
      values (s.obra_id, s.datos->>'etapa', coalesce(s.datos->>'requerimiento', 'REGULAR'), (s.datos->>'item_id')::bigint,
              (s.datos->>'cantidad')::numeric, nullif(s.datos->>'pu', '')::numeric);
    elsif s.tipo = 'BAJA_PARTIDA' then
      -- Las órdenes de la partida se anulan; si alguna ya se pagó o tiene comprobante, no se puede.
      for r in select distinct o.obra_id, o.numero, o.estado,
                      exists (select 1 from oc_items x where x.obra_id = o.obra_id and x.numero_oc = o.numero and x.comprobante_id is not null) as con_comprobante,
                      exists (select 1 from pago_aplicaciones ap where ap.obra_id = o.obra_id and ap.numero_oc = o.numero) as con_pago
                 from oc_items l join ordenes_compra o on o.obra_id = l.obra_id and o.numero = l.numero_oc
                where l.partida_id = s.partida_id and o.estado <> 'ANULADA' loop
        if r.estado in ('PAGADA', 'EN_ENTREGA', 'RECIBIDA') or r.con_pago then
          raise exception 'La orden % ya está pagada: la partida no se puede dar de baja', r.numero;
        end if;
        if r.con_comprobante then
          raise exception 'La orden % tiene comprobante registrado: Logística debe anularlo antes de dar de baja la partida', r.numero;
        end if;
        perform anular_orden(r.obra_id, r.numero, 'Baja de partida aprobada por Gerencia');
      end loop;
      -- Si tuvo órdenes (ahora anuladas) la partida queda de baja; si no, se borra.
      if exists (select 1 from oc_items where partida_id = s.partida_id) then
        update partidas set dada_de_baja_at = now() where id = s.partida_id;
      else
        delete from partidas where id = s.partida_id;
      end if;
    elsif s.tipo = 'PERSONA_ALTA' then
      update personas set estado = 'ACTIVA' where id = s.persona_id;
    elsif s.tipo = 'PERSONA_CAMBIO' then
      update personas
         set nombre = coalesce(upper(nullif(btrim(s.datos->>'nombre'), '')), nombre),
             cargo = coalesce(s.datos->>'cargo', cargo),
             telefono = case when s.datos ? 'telefono' then nullif(btrim(s.datos->>'telefono'), '') else telefono end,
             correo = case when s.datos ? 'correo' then nullif(lower(btrim(s.datos->>'correo')), '') else correo end
       where id = s.persona_id;
    elsif s.tipo = 'PERSONA_BAJA' then
      update personas set estado = 'BAJA' where id = s.persona_id;
      delete from perfil_obras where user_id = (select user_id from personas where id = s.persona_id);
    end if;
  elsif s.tipo = 'PERSONA_ALTA' then
    -- alta rechazada: la persona no llega a existir como activa
    update personas set estado = 'BAJA' where id = s.persona_id;
  end if;

  update solicitudes set estado = case when p_aprobar then 'APROBADA' else 'RECHAZADA' end,
                         respuesta = nullif(btrim(coalesce(p_respuesta, '')), ''), resuelto_by = auth.uid(), resuelto_at = now()
   where id = p_id;

  v_titulo := format('%s: %s',
    case s.tipo when 'ADICIONAL' then 'Adicional' when 'BAJA_PARTIDA' then 'Baja de partida'
                when 'PERSONA_ALTA' then 'Alta de persona' when 'PERSONA_CAMBIO' then 'Cambio de persona' else 'Baja de persona' end,
    case when s.tipo in ('ADICIONAL', 'PERSONA_CAMBIO') then case when p_aprobar then 'aprobado' else 'rechazado' end
         else case when p_aprobar then 'aprobada' else 'rechazada' end end);
  perform notificar_usuario(s.solicitado_by, 'SOLICITUD_RESUELTA', v_titulo,
                            coalesce(nullif(btrim(coalesce(p_respuesta, '')), ''), s.datos->>'descripcion',
                                     (select descripcion from items where id = (s.datos->>'item_id')::bigint),
                                     (select nombre from personas where id = s.persona_id)),
                            case when s.tipo like 'PERSONA%' then '/rrhh' else '/operaciones/solicitudes' end);
end;
$function$;

create or replace view public.v_seguimiento_partida with (security_invoker = true) as
WITH lineas AS (
         SELECT l.partida_id,
            l.cantidad,
            o.estado,
            o.entrega_cerrada_at,
            COALESCE(( SELECT sum(en.cantidad) AS sum
                   FROM entregas en
                  WHERE (en.oc_item_id = l.id)), (0)::numeric) AS entregado
           FROM (oc_items l
             JOIN ordenes_compra o ON (((o.obra_id = l.obra_id) AND (o.numero = l.numero_oc))))
          WHERE (o.estado <> ALL (ARRAY['ANULADA'::estado_oc, 'BORRADOR'::estado_oc]))
        ), x AS (
         SELECT lineas.partida_id,
            sum(
                CASE
                    WHEN (lineas.estado = ANY (ARRAY['EMITIDA'::estado_oc, 'PRECIOS_CONFIRMADOS'::estado_oc, 'FACTURADA'::estado_oc])) THEN lineas.cantidad
                    ELSE (0)::numeric
                END) AS en_logistica,
            sum(
                CASE
                    WHEN (lineas.estado = ANY (ARRAY['EN_TESORERIA'::estado_oc, 'PAGADA'::estado_oc])) THEN lineas.cantidad
                    ELSE (0)::numeric
                END) AS en_tesoreria,
            sum(
                CASE
                    WHEN ((lineas.estado = ANY (ARRAY['EN_ENTREGA'::estado_oc, 'RECIBIDA'::estado_oc])) AND (lineas.entrega_cerrada_at IS NULL)) THEN GREATEST((lineas.cantidad - lineas.entregado), (0)::numeric)
                    ELSE (0)::numeric
                END) AS por_recibir,
            sum(lineas.entregado) AS recibido
           FROM lineas
          GROUP BY lineas.partida_id
        )
 SELECT p.id AS partida_id,
    p.obra_id,
    p.etapa,
    p.requerimiento,
    p.item_id,
    i.descripcion,
    i.unidad,
    i.rubro,
        CASE
            WHEN (i.rubro = 'MATERIAL'::rubro) THEN 'MATERIALES'::text
            WHEN (i.rubro = 'MANO OBRA'::rubro) THEN 'MANO_OBRA'::text
            ELSE 'SUBCONTRATOS'::text
        END AS grupo,
    p.cantidad AS presupuestado,
    p.pu,
    COALESCE(x.en_logistica, (0)::numeric) AS en_logistica,
    COALESCE(x.en_tesoreria, (0)::numeric) AS en_tesoreria,
    COALESCE(x.por_recibir, (0)::numeric) AS por_recibir,
    COALESCE(x.recibido, (0)::numeric) AS recibido,
    GREATEST(((((ef.efectivo - COALESCE(x.en_logistica, (0)::numeric)) - COALESCE(x.en_tesoreria, (0)::numeric)) - COALESCE(x.por_recibir, (0)::numeric)) - COALESCE(x.recibido, (0)::numeric)), (0)::numeric) AS por_pedir,
    ef.efectivo AS presupuesto_efectivo,
    ef.recibido AS adelanto_recibido,
    ef.dado AS adelanto_dado,
    COALESCE(( SELECT sum(ri.cantidad) FROM requerimientos_obra_items ri JOIN requerimientos_obra rq ON rq.id = ri.requerimiento_id
       WHERE ri.partida_id = p.id AND rq.estado = 'VIGENTE'), (0)::numeric) AS requerido,
    fn_orden_etapa(p.obra_id, p.etapa) AS orden_etapa
   FROM (((partidas p
     JOIN items i ON ((i.id = p.item_id)))
     JOIN v_presupuesto_efectivo ef ON ((ef.partida_id = p.id)))
     LEFT JOIN x ON ((x.partida_id = p.id)))
  WHERE (p.dada_de_baja_at IS NULL);

create or replace function public.crear_requerimiento(p_obra_id bigint, p_nota text, p_lineas jsonb)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id bigint;
  v_numero text;
  l record;
  a record;
  v_p record;
  v_o record;
  v_disp numeric;
  v_adel numeric;
  v_falta numeric;
  v_disp_origen numeric;
begin
  if rol_actual() not in ('OPERACIONES', 'JEFE_OPERACIONES', 'ADMIN') then
    raise exception 'Solo Operaciones crea requerimientos';
  end if;
  if not exists (select 1 from obras where id = p_obra_id and presupuesto_estado = 'PUBLICADO') then
    raise exception 'La obra no tiene el presupuesto publicado';
  end if;
  if p_lineas is null or jsonb_typeof(p_lineas) <> 'array' or jsonb_array_length(p_lineas) = 0 then
    raise exception 'El requerimiento debe tener al menos una partida';
  end if;
  perform 1 from obras where id = p_obra_id for update;  -- numeración sin carreras
  v_numero := 'REQ-' || lpad(((select count(*) from requerimientos_obra where obra_id = p_obra_id) + 1)::text, 3, '0');
  insert into requerimientos_obra (obra_id, numero, nota) values (p_obra_id, v_numero, nullif(btrim(coalesce(p_nota, '')), ''))
  returning id into v_id;

  for l in
    select (x->>'partida_id')::bigint as partida_id, (x->>'cantidad')::numeric as cantidad, coalesce(x->'adelantos', '[]'::jsonb) as adelantos
      from jsonb_array_elements(p_lineas) x
     order by (x->>'partida_id')::bigint
  loop
    if l.partida_id is null or coalesce(l.cantidad, 0) <= 0 then
      raise exception 'Cada partida necesita una cantidad mayor que cero';
    end if;
    select p.id, p.obra_id, p.item_id, p.etapa, i.descripcion, i.unidad into v_p
      from partidas p join items i on i.id = p.item_id where p.id = l.partida_id and p.dada_de_baja_at is null for update of p;
    if not found or v_p.obra_id <> p_obra_id then
      raise exception 'La partida % no es de esta obra', l.partida_id;
    end if;
    v_disp := fn_presupuesto_efectivo(v_p.id) - fn_requerido_partida(v_p.id);
    v_falta := greatest(l.cantidad - v_disp, 0);
    select coalesce(sum((y->>'cantidad')::numeric), 0) into v_adel from jsonb_array_elements(l.adelantos) y;
    if v_falta > 0.0001 and v_adel < v_falta - 0.0001 then
      raise exception '% en %: faltan % % en el presupuesto. Adelanta de una etapa posterior o pide un adicional',
        v_p.descripcion, v_p.etapa, trim_scale(round(v_falta - v_adel, 4)), v_p.unidad;
    end if;
    if v_adel > v_falta + 0.0001 then
      raise exception '% en %: el adelanto (%) supera lo que falta (%)', v_p.descripcion, v_p.etapa, trim_scale(v_adel), trim_scale(round(v_falta, 4));
    end if;
    for a in select (y->>'partida_origen_id')::bigint as origen, (y->>'cantidad')::numeric as cantidad from jsonb_array_elements(l.adelantos) y loop
      if coalesce(a.cantidad, 0) <= 0 then
        raise exception 'Cada adelanto necesita una cantidad mayor que cero';
      end if;
      select p.id, p.obra_id, p.item_id, p.etapa into v_o from partidas p where p.id = a.origen and p.dada_de_baja_at is null for update;
      if not found or v_o.obra_id <> p_obra_id or v_o.item_id <> v_p.item_id then
        raise exception 'Solo se adelanta el mismo ítem de la misma obra';
      end if;
      if fn_orden_etapa(p_obra_id, v_o.etapa) <= fn_orden_etapa(p_obra_id, v_p.etapa) then
        raise exception 'Solo se adelanta de una etapa posterior a % (se pidió de %)', v_p.etapa, v_o.etapa;
      end if;
      v_disp_origen := fn_presupuesto_efectivo(v_o.id) - greatest(fn_requerido_partida(v_o.id), fn_comprometido_partida(v_o.id));
      if a.cantidad > v_disp_origen + 0.0001 then
        raise exception 'La etapa % solo puede adelantar % % de %', v_o.etapa, trim_scale(round(greatest(v_disp_origen, 0), 4)), v_p.unidad, v_p.descripcion;
      end if;
      insert into adelantos (obra_id, item_id, partida_origen_id, partida_destino_id, cantidad, requerimiento_id)
      values (p_obra_id, v_p.item_id, v_o.id, v_p.id, a.cantidad, v_id);
    end loop;
    insert into requerimientos_obra_items (requerimiento_id, partida_id, cantidad) values (v_id, v_p.id, l.cantidad);
  end loop;

  perform notificar('LOGISTICA', 'REQUERIMIENTO', format('Requerimiento %s', v_numero),
                    (select nombre from obras where id = p_obra_id), format('/logistica/requerimientos?obra=%s', p_obra_id));
  return v_id;
end;
$$;

create or replace function public.anular_requerimiento(p_id bigint, p_motivo text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  q requerimientos_obra%rowtype;
  r record;
begin
  select * into q from requerimientos_obra where id = p_id for update;
  if not found or q.estado <> 'VIGENTE' then
    raise exception 'El requerimiento ya está anulado';
  end if;
  if not (q.created_by = auth.uid() or rol_actual() in ('JEFE_OPERACIONES', 'ADMIN')) then
    raise exception 'Solo quien lo creó o el Jefe de Operaciones lo anula';
  end if;
  update requerimientos_obra set estado = 'ANULADO', anulado_by = auth.uid(), anulado_at = now(),
                            motivo_anulacion = nullif(btrim(coalesce(p_motivo, '')), '')
   where id = p_id;
  -- Sin sus adelantos, ninguna partida puede quedar con más comprado que su presupuesto.
  for r in select distinct partida_destino_id as id from adelantos where requerimiento_id = p_id loop
    if fn_comprometido_partida(r.id) > fn_presupuesto_efectivo(r.id) + 0.0001 then
      raise exception 'No se puede anular: lo adelantado ya se compró en %', (select etapa || ' ' || i.descripcion from partidas p join items i on i.id = p.item_id where p.id = r.id);
    end if;
  end loop;
end;
$$;

