-- Líneas de requerimiento con lo atendido: lo comprometido de cada partida se reparte primero a
-- los requerimientos_obra más antiguos.
create or replace view public.v_requerimiento_items with (security_invoker = true) as
with req as (
  select ri.id, ri.requerimiento_id, ri.partida_id, ri.cantidad, q.obra_id, q.numero, q.created_at,
         sum(ri.cantidad) over (partition by ri.partida_id order by q.created_at, ri.id) as acumulado
    from public.requerimientos_obra_items ri
    join public.requerimientos_obra q on q.id = ri.requerimiento_id
   where q.estado = 'VIGENTE'
)
select req.id, req.requerimiento_id, req.numero, req.obra_id, req.partida_id, req.created_at,
       p.etapa, i.descripcion, i.unidad, i.rubro,
       case when i.rubro = 'MATERIAL' then 'MATERIALES' when i.rubro = 'MANO OBRA' then 'MANO_OBRA' else 'SUBCONTRATOS' end as grupo,
       req.cantidad as requerido,
       least(req.cantidad, greatest(public.fn_comprometido_partida(req.partida_id) - (req.acumulado - req.cantidad), 0)) as atendido,
       req.cantidad - least(req.cantidad, greatest(public.fn_comprometido_partida(req.partida_id) - (req.acumulado - req.cantidad), 0)) as pendiente,
       public.fn_orden_etapa(req.obra_id, p.etapa) as orden_etapa
  from req
  join public.partidas p on p.id = req.partida_id
  join public.items i on i.id = p.item_id;
grant select on public.v_requerimiento_items to authenticated;
