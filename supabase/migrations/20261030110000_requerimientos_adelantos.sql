-- Requerimientos de Operaciones, orden de etapas por obra y adelantos de material (29/10/2026).
--   * obra_etapas: el orden de las etapas de cada obra (lo gestiona el Jefe de Operaciones).
--   * requerimientos_obra: Operaciones pide parte del presupuesto; Logística los consulta (sin vínculo
--     con las órdenes; lo atendido se calcula por partida).
--   * adelantos: a una etapa le falta material y lo toma del mismo ítem de una etapa posterior.
--     El total del ítem no cambia; cambia el presupuesto efectivo de cada partida.

-- ============================================================ orden de etapas por obra
create table public.obra_etapas (
  obra_id bigint not null references public.obras (id) on delete cascade,
  etapa   text   not null references public.etapas (codigo) on update cascade,
  orden   integer not null,
  primary key (obra_id, etapa)
);
alter table public.obra_etapas enable row level security;
create policy obra_etapas_select on public.obra_etapas for select to authenticated using (true);
grant select on public.obra_etapas to authenticated;

insert into public.obra_etapas (obra_id, etapa, orden)
select distinct p.obra_id, p.etapa, e.orden * 10
  from public.partidas p join public.etapas e on e.codigo = p.etapa
on conflict do nothing;

-- Una etapa nueva en la obra toma su lugar del orden general (el Jefe puede reordenarla después).
create or replace function public.fn_obra_etapa_nueva()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  insert into obra_etapas (obra_id, etapa, orden)
  values (new.obra_id, new.etapa, coalesce((select orden from etapas where codigo = new.etapa), 0) * 10)
  on conflict do nothing;
  return new;
end;
$$;
create trigger partidas_obra_etapa after insert or update of etapa on public.partidas
  for each row execute function public.fn_obra_etapa_nueva();

create or replace function public.fn_orden_etapa(p_obra_id bigint, p_etapa text)
returns integer
language sql
stable
set search_path = public
as $$
  select coalesce((select orden from obra_etapas where obra_id = p_obra_id and etapa = p_etapa),
                  100000 + coalesce((select orden from etapas where codigo = p_etapa), 0));
$$;

create or replace function public.ordenar_etapas_obra(p_obra_id bigint, p_etapas text[])
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if rol_actual() not in ('JEFE_OPERACIONES', 'ADMIN') then
    raise exception 'Solo el Jefe de Operaciones ordena las etapas';
  end if;
  if exists (select 1 from obra_etapas where obra_id = p_obra_id and etapa <> all (p_etapas)) then
    raise exception 'Faltan etapas de la obra en el nuevo orden';
  end if;
  insert into obra_etapas (obra_id, etapa, orden)
  select p_obra_id, e, n * 10 from unnest(p_etapas) with ordinality as t(e, n)
  on conflict (obra_id, etapa) do update set orden = excluded.orden;
end;
$$;

