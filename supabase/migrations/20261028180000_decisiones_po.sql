-- Logística corrige un comprobante (p. ej. tras un rechazo). Mientras no esté contabilizado ni pagado.
create or replace function public.editar_comprobante(
  p_id bigint, p_tipo tipo_comprobante, p_serie text, p_numero text, p_fecha date,
  p_total numeric, p_retencion numeric, p_archivo_path text, p_motivo text
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  c comprobantes%rowtype;
  v_antes jsonb;
  v_despues jsonb;
begin
  if coalesce((select rol::text from perfiles where user_id = auth.uid()), '') not in ('LOGISTICA', 'ADMIN') then
    raise exception 'Solo Logística corrige comprobantes';
  end if;
  select * into c from comprobantes where id = p_id for update;
  if not found then
    raise exception 'El comprobante no existe';
  end if;
  if exists (select 1 from asientos where comprobante_id = p_id) then
    raise exception 'El comprobante ya está contabilizado: pide a Contabilidad que lo revise';
  end if;
  if exists (select 1 from pago_aplicaciones where comprobante_id = p_id) then
    raise exception 'El comprobante ya tiene pagos';
  end if;
  if p_total is null or p_total <= 0 or coalesce(p_retencion, 0) < 0 or coalesce(p_retencion, 0) >= p_total then
    raise exception 'Revisa el total y la retención';
  end if;

  v_antes := jsonb_build_object('tipo', c.tipo, 'serie', c.serie, 'numero', c.numero, 'fecha_emision', c.fecha_emision,
                                'total', c.total, 'retencion', c.retencion, 'archivo_path', c.archivo_path);
  update comprobantes
     set tipo = p_tipo, serie = upper(btrim(p_serie)), numero = coalesce(nullif(ltrim(btrim(p_numero), '0'), ''), '0'),
         fecha_emision = p_fecha, total = round(p_total, 2), retencion = round(coalesce(p_retencion, 0), 2),
         archivo_path = coalesce(nullif(btrim(p_archivo_path), ''), archivo_path),
         -- el trigger vuelve a calcular base e IGV
         base = null, igv = null,
         periodo_anotacion = greatest(periodo_anotacion, to_char(p_fecha, 'YYYYMM'))
   where id = p_id
  returning jsonb_build_object('tipo', tipo, 'serie', serie, 'numero', numero, 'fecha_emision', fecha_emision,
                               'total', total, 'retencion', retencion, 'archivo_path', archivo_path) into v_despues;
  if v_antes is distinct from v_despues then
    insert into comprobantes_historial (comprobante_id, anterior, nuevo, motivo)
    values (p_id, v_antes, v_despues, nullif(btrim(coalesce(p_motivo, '')), ''));
  end if;
exception when unique_violation then
  raise exception 'Ya existe un comprobante con esa serie y número para el proveedor';
end;
$$;

-- ============================================================ guía obligatoria para pagar
-- Cualquier pago (a la orden o a sus comprobantes) de una OC que requiere guía exige la guía emitida.
create or replace function public.fn_pago_exige_guia()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_numero text;
begin
  select o.numero into v_numero
    from ordenes_compra o
   where o.requiere_guia and o.tipo = 'OC'
     and ((new.obra_id is not null and o.obra_id = new.obra_id and o.numero = new.numero_oc)
          or (new.comprobante_id is not null and (o.obra_id, o.numero) in
                (select l.obra_id, l.numero_oc from oc_items l where l.comprobante_id = new.comprobante_id)))
     and not exists (select 1 from guias g where g.obra_id = o.obra_id and g.numero_oc = o.numero and g.estado = 'EMITIDA')
   limit 1;
  if v_numero is not null then
    raise exception 'La OC % requiere guía de remisión: Contabilidad debe emitirla antes del pago', v_numero;
  end if;
  return new;
end;
$$;
create trigger pago_aplicaciones_exige_guia before insert on public.pago_aplicaciones
  for each row execute function public.fn_pago_exige_guia();

-- ============================================================ cierre de entrega incompleta (Operaciones)
create or replace function public.cerrar_entrega(p_obra_id bigint, p_numero text, p_motivo text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if coalesce((select rol::text from perfiles where user_id = auth.uid()), '') not in ('OPERACIONES', 'GERENCIA', 'ADMIN') then
    raise exception 'Solo Operaciones cierra una entrega incompleta';
  end if;
  if nullif(btrim(coalesce(p_motivo, '')), '') is null then
    raise exception 'Indica el motivo';
  end if;
  update ordenes_compra
     set estado = 'RECIBIDA', entrega_cerrada_at = now(), entrega_cerrada_motivo = btrim(p_motivo), entrega_cerrada_by = auth.uid()
   where obra_id = p_obra_id and numero = p_numero and estado = 'EN_ENTREGA';
  if not found then
    raise exception 'La orden % no está en entrega', p_numero;
  end if;
  perform notificar('LOGISTICA', 'ENTREGA_CERRADA', format('Entrega cerrada incompleta: %s', p_numero), btrim(p_motivo),
                    format('/logistica/ordenes/%s/%s', p_obra_id, p_numero));
end;
$$;

-- ============================================================ personas: contacto sin aprobación
create or replace function public.actualizar_contacto_persona(p_id bigint, p_telefono text, p_correo text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if coalesce((select rol::text from perfiles where user_id = auth.uid()), '') not in ('RRHH', 'ADMIN') then
    raise exception 'Solo Recursos Humanos gestiona personas';
  end if;
  if coalesce(p_correo, '') <> '' and p_correo !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'Correo inválido';
  end if;
  update personas set telefono = nullif(btrim(coalesce(p_telefono, '')), ''), correo = nullif(lower(btrim(coalesce(p_correo, ''))), '')
   where id = p_id and estado = 'ACTIVA';
  if not found then
    raise exception 'La persona no está activa';
  end if;
end;
$$;

