--   * Tesorería rechaza → la orden vuelve a cotización; el comprobante queda y Logística puede
--     corregirlo (cada edición deja una copia en el historial).
--   * Una OC que requiere guía no se paga sin la guía emitida.
--   * La baja de una partida con órdenes las anula al aprobarse (no si ya hay compras pagadas).
--   * Operaciones puede cerrar una entrega incompleta; lo que no llegó vuelve al saldo de la partida.
--   * Teléfono y correo de una persona se cambian sin aprobación.
--   * Al ingeniero de Obras lo asigna Gerencia.
--   * La guía indica quién transporta: el proveedor, nosotros o un transportista que contrata el proveedor.

