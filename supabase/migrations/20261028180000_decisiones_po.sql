create or replace view public.v_partidas with (security_invoker = true) as
SELECT p.id,
    p.codigo,
    p.obra_id,
    ob.nombre AS obra,
    ob.empresa_id,
    p.etapa,
    p.requerimiento,
    p.item_id,
    i.descripcion,
    i.unidad,
    i.rubro,
    p.cantidad,
    p.pu,
    round(p.cantidad * p.pu, 2) AS parcial,
    round(fn_pu_max(p.pu, i.tolerancia_pct), 4) AS pu_max,
    COALESCE(x.cant, 0::numeric) AS cant_comprometida,
    COALESCE(x.monto, 0::numeric) AS monto_ejecutado,
    p.cantidad - COALESCE(x.cant, 0::numeric) AS saldo_cant,
    COALESCE(round(p.cantidad * p.pu, 2), 0::numeric) - COALESCE(x.monto, 0::numeric) AS saldo_monto,
        CASE
            WHEN p.cantidad > 0::numeric THEN round(COALESCE(x.cant, 0::numeric) / p.cantidad, 4)
            ELSE NULL::numeric
        END AS avance,
    i.tipo_material
   FROM partidas p
     JOIN obras ob ON ob.id = p.obra_id
     JOIN items i ON i.id = p.item_id
     LEFT JOIN LATERAL ( SELECT sum(CASE WHEN oc.entrega_cerrada_at IS NULL THEN c.cantidad ELSE COALESCE((SELECT sum(en.cantidad) FROM entregas en WHERE en.oc_item_id = c.id), 0::numeric) END) AS cant,
            sum(CASE WHEN oc.entrega_cerrada_at IS NULL THEN COALESCE(c.parcial, 0::numeric)
                     ELSE round(COALESCE((SELECT sum(en.cantidad) FROM entregas en WHERE en.oc_item_id = c.id), 0::numeric) * COALESCE(c.pu_efectivo, 0::numeric), 2) END) AS monto
           FROM v_oc_items_calc c
             JOIN ordenes_compra oc ON oc.obra_id = c.obra_id AND oc.numero = c.numero_oc
          WHERE c.partida_id = p.id AND (c.estado <> ALL (ARRAY['ANULADA'::estado_oc, 'BORRADOR'::estado_oc]))) x ON true
  WHERE p.dada_de_baja_at IS NULL;
create or replace view public.v_avance_partida with (security_invoker = true) as
SELECT p.id AS partida_id,
    p.obra_id,
    p.etapa,
    p.requerimiento,
    p.item_id,
    i.descripcion,
    i.unidad,
    i.rubro,
    p.cantidad AS presupuestado,
    p.pu,
    round(p.cantidad * p.pu, 2) AS parcial,
    COALESCE(c.comprado, 0::numeric) AS comprado,
    COALESCE(c.monto_comprado, 0::numeric) AS monto_comprado,
    COALESCE(e.llegado, 0::numeric) AS llegado,
    COALESCE(e.fotos, 0::bigint) AS fotos
   FROM partidas p
     JOIN items i ON i.id = p.item_id
     LEFT JOIN LATERAL ( SELECT sum(CASE WHEN oc.entrega_cerrada_at IS NULL THEN l.cantidad
                     ELSE COALESCE((SELECT sum(en.cantidad) FROM entregas en WHERE en.oc_item_id = l.id), 0::numeric) END) AS comprado,
            sum(CASE WHEN oc.entrega_cerrada_at IS NULL THEN COALESCE(l.parcial, 0::numeric)
                     ELSE round(COALESCE((SELECT sum(en.cantidad) FROM entregas en WHERE en.oc_item_id = l.id), 0::numeric) * COALESCE(l.pu_efectivo, 0::numeric), 2) END) AS monto_comprado
           FROM v_oc_items_calc l
                     JOIN ordenes_compra oc ON oc.obra_id = l.obra_id AND oc.numero = l.numero_oc
          WHERE l.partida_id = p.id AND l.estado <> 'ANULADA'::estado_oc) c ON true
     LEFT JOIN LATERAL ( SELECT sum(en.cantidad) AS llegado,
            ( SELECT count(*) AS count
                   FROM entrega_fotos f
                     JOIN entregas e2 ON e2.id = f.entrega_id
                     JOIN oc_items l2 ON l2.id = e2.oc_item_id
                  WHERE l2.partida_id = p.id) AS fotos
           FROM entregas en
             JOIN oc_items l ON l.id = en.oc_item_id
          WHERE l.partida_id = p.id) e ON true
  WHERE p.dada_de_baja_at IS NULL;
create or replace view public.v_por_pagar with (security_invoker = true) as
WITH lin AS (
         SELECT c.obra_id,
            c.numero_oc,
            COALESCE(sum(COALESCE(c.parcial, 0::numeric)) FILTER (WHERE c.comprobante_id IS NULL), 0::numeric) AS sin_comp,
            bool_or(c.comprobante_id IS NULL) AS falta,
            array_agg(DISTINCT c.etapa) AS etapas
           FROM v_oc_items_calc c
          GROUP BY c.obra_id, c.numero_oc
        ), cp AS (
         SELECT x.obra_id,
            x.numero_oc,
            count(*) AS n,
            sum(x.neto_orden) AS neto,
            sum(x.saldo_orden) AS saldo
           FROM v_orden_comprobantes x
          GROUP BY x.obra_id, x.numero_oc
        ), dir AS (
         SELECT ap.obra_id,
            ap.numero_oc,
            sum(ap.monto) AS pagado
           FROM pago_aplicaciones ap
          WHERE ap.obra_id IS NOT NULL
          GROUP BY ap.obra_id, ap.numero_oc
        ), ctr AS (
         SELECT DISTINCT a.obra_id,
            a.numero_oc
           FROM adjuntos a
          WHERE a.tipo = 'CONTRATO'::tipo_adjunto
        ), ord AS (
         SELECT o.obra_id,
            o.numero,
            o.tipo,
            o.proveedor_id,
            o.fecha,
            o.estado,
            o.token_cotizacion,
            o.motivo_anulacion,
            o.created_by,
            o.updated_by,
            o.created_at,
            o.updated_at,
            COALESCE(cp.neto, 0::numeric) + COALESCE(lin.sin_comp, 0::numeric) AS total,
            GREATEST(0::numeric, COALESCE(cp.saldo, 0::numeric) + COALESCE(lin.sin_comp, 0::numeric) - COALESCE(dir.pagado, 0::numeric)) AS saldo,
            COALESCE(cp.n, 0::bigint)::integer AS n_comprobantes,
            ctr.obra_id IS NOT NULL AS tiene_contrato,
            COALESCE(lin.falta, false) AS falta_comprobante,
            lin.etapas
           FROM ordenes_compra o
             LEFT JOIN lin ON lin.obra_id = o.obra_id AND lin.numero_oc = o.numero
             LEFT JOIN cp ON cp.obra_id = o.obra_id AND cp.numero_oc = o.numero
             LEFT JOIN dir ON dir.obra_id = o.obra_id AND dir.numero_oc = o.numero
             LEFT JOIN ctr ON ctr.obra_id = o.obra_id AND ctr.numero_oc = o.numero
          WHERE o.estado = ANY (ARRAY['EN_TESORERIA'::estado_oc, 'PAGADA'::estado_oc, 'EN_ENTREGA'::estado_oc, 'RECIBIDA'::estado_oc])
        )
 SELECT o.tipo::text AS doc,
    o.obra_id,
    o.numero,
    NULL::bigint AS orden_pago_id,
    ob.empresa_id,
    e.nombre AS empresa,
    ob.nombre AS obra,
    o.proveedor_id,
    pr.razon_social AS proveedor,
    pr.ruc_o_cod AS ruc,
    pr.banco,
    pr.cuenta_bancaria,
    o.fecha,
    o.total,
    o.total - o.saldo AS pagado,
    o.saldo,
    o.n_comprobantes,
    o.tiene_contrato,
    o.falta_comprobante,
        CASE
            WHEN o.estado = 'EN_TESORERIA'::estado_oc AND o.saldo > 0.005 THEN 'PENDIENTE'::text
            ELSE 'PAGADO'::text
        END AS estado,
    o.etapas,
    o.tipo = 'OC'::tipo_orden AND (EXISTS ( SELECT 1 FROM ordenes_compra x WHERE x.obra_id = o.obra_id AND x.numero = o.numero AND x.requiere_guia))
      AND NOT (EXISTS ( SELECT 1 FROM guias g WHERE g.obra_id = o.obra_id AND g.numero_oc = o.numero AND g.estado = 'EMITIDA'::text)) AS falta_guia
   FROM ord o
     JOIN obras ob ON ob.id = o.obra_id
     JOIN empresas e ON e.id = ob.empresa_id
     JOIN proveedores pr ON pr.id = o.proveedor_id
  WHERE o.estado <> 'EN_TESORERIA'::estado_oc OR o.saldo > 0.005 OR o.total > 0.005
UNION ALL
 SELECT 'OP'::text AS doc,
    op.obra_id,
    op.numero,
    op.id AS orden_pago_id,
    ob.empresa_id,
    e.nombre AS empresa,
    ob.nombre AS obra,
    op.proveedor_id,
    pr.razon_social AS proveedor,
    pr.ruc_o_cod AS ruc,
    pr.banco,
    pr.cuenta_bancaria,
    op.fecha,
    op.monto AS total,
    COALESCE(pa.pagado, 0::numeric) AS pagado,
    GREATEST(0::numeric, op.monto - COALESCE(pa.pagado, 0::numeric)) AS saldo,
    0 AS n_comprobantes,
    false AS tiene_contrato,
    false AS falta_comprobante,
        CASE
            WHEN op.estado = 'PAGADA'::text THEN 'PAGADO'::text
            ELSE 'PENDIENTE'::text
        END AS estado,
    NULL::text[] AS etapas,
    false AS falta_guia
   FROM ordenes_pago op
     JOIN obras ob ON ob.id = op.obra_id
     JOIN empresas e ON e.id = ob.empresa_id
     JOIN proveedores pr ON pr.id = op.proveedor_id
     LEFT JOIN ( SELECT ap.orden_pago_id,
            sum(ap.monto) AS pagado
           FROM pago_aplicaciones ap
          WHERE ap.orden_pago_id IS NOT NULL
          GROUP BY ap.orden_pago_id) pa ON pa.orden_pago_id = op.id
  WHERE op.estado = ANY (ARRAY['EN_TESORERIA'::text, 'PAGADA'::text]);

