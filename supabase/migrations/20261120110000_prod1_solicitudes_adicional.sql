-- Prod 1: Logística pide adicionales y Gerencia los aprueba (antes los agregaba solo Gerencia, directo; lo sigue pudiendo).
-- Una solicitud es un adicional completo: la obra, una o varias partidas (etapa, ítem, cantidad y P.U.) y el motivo. Al
-- aprobarla se vuelve el siguiente «ADIC n» de la obra con agregar_adicional (las mismas validaciones y el mismo aviso a
-- Logística); al rechazarla, con su motivo, Logística recibe el aviso. Tablas propias de prod 1 (la «solicitudes» del MVP
-- es una partida por solicitud y la resuelve otro flujo): no se toca.

create table public.adicional_solicitudes (
  id            bigint generated by default as identity primary key,
  obra_id       bigint not null references public.obras (id),
  motivo        text not null check (btrim(motivo) <> ''),
  estado        text not null default 'PENDIENTE' check (estado in ('PENDIENTE', 'APROBADA', 'RECHAZADA')),
  -- El «ADIC n» que le tocó al aprobarse.
  requerimiento text,
  -- El motivo del rechazo.
  respuesta     text,
  solicitado_by uuid not null default auth.uid() references auth.users (id),
  solicitado_at timestamptz not null default now(),
  resuelto_by   uuid references auth.users (id),
  resuelto_at   timestamptz,
  check (estado <> 'APROBADA' or requerimiento is not null),
  check (estado <> 'RECHAZADA' or btrim(coalesce(respuesta, '')) <> '')
);
create index adicional_solicitudes_estado_idx on public.adicional_solicitudes (estado, solicitado_at desc);
create index adicional_solicitudes_obra_idx on public.adicional_solicitudes (obra_id);

create table public.adicional_solicitud_partidas (
  id           bigint generated by default as identity primary key,
  solicitud_id bigint not null references public.adicional_solicitudes (id) on delete cascade,
  etapa        text not null references public.etapas (codigo) on update cascade,
  item_id      bigint not null references public.items (id),
  cantidad     numeric(14,4) not null check (cantidad > 0),
  pu           numeric(12,4) not null check (pu >= 0)
);
create index adicional_solicitud_partidas_sol_idx on public.adicional_solicitud_partidas (solicitud_id);

-- Las leen Logística y Gerencia (y el Admin); llevan precios: Operaciones no. Se escriben solo por las funciones.
alter table public.adicional_solicitudes enable row level security;
alter table public.adicional_solicitud_partidas enable row level security;
revoke all on public.adicional_solicitudes, public.adicional_solicitud_partidas from anon, authenticated;
grant select on public.adicional_solicitudes, public.adicional_solicitud_partidas to authenticated;
create policy adicional_solicitudes_select on public.adicional_solicitudes for select to authenticated
  using ((select public.rol_en('LOGISTICA', 'GERENCIA')));
create policy adicional_solicitud_partidas_select on public.adicional_solicitud_partidas for select to authenticated
  using ((select public.rol_en('LOGISTICA', 'GERENCIA')));

create trigger audit_adicional_solicitudes after insert or update or delete on public.adicional_solicitudes
  for each row execute function public.fn_audit();
create trigger audit_adicional_solicitud_partidas after insert or update or delete on public.adicional_solicitud_partidas
  for each row execute function public.fn_audit();

-- Logística pide un adicional. Las mismas reglas que agregar_adicional, para que Gerencia no apruebe algo imposible.
create or replace function public.pedir_adicional(p_obra_id bigint, p_partidas jsonb, p_motivo text)
  returns bigint language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_obra obras%rowtype;
  v_id bigint;
  v_n int;
  v_total numeric;
begin
  if rol_actual() not in ('LOGISTICA', 'ADMIN') then
    raise exception 'Solo Logística pide adicionales';
  end if;
  if btrim(coalesce(p_motivo, '')) = '' then
    raise exception 'Escribe el motivo del adicional';
  end if;
  select * into v_obra from obras where id = p_obra_id;
  if not found then
    raise exception 'La obra no existe';
  end if;
  if v_obra.estado = 'CERRADA' then
    raise exception 'La obra está cerrada';
  end if;
  if v_obra.presupuesto_estado <> 'PUBLICADO' then
    raise exception 'La obra aún no tiene el presupuesto publicado';
  end if;
  if p_partidas is null or jsonb_typeof(p_partidas) <> 'array' or jsonb_array_length(p_partidas) = 0 then
    raise exception 'El adicional necesita al menos una partida';
  end if;
  if exists (select 1 from jsonb_to_recordset(p_partidas) x(etapa text, item_id bigint, cantidad numeric, pu numeric)
              where x.etapa is null or x.item_id is null or x.cantidad is null or x.cantidad <= 0 or x.pu is null or x.pu < 0
                 or not exists (select 1 from etapas e where e.codigo = x.etapa)
                 or not exists (select 1 from items i where i.id = x.item_id)) then
    raise exception 'Cada partida del adicional necesita etapa, ítem, cantidad y P.U. válidos';
  end if;

  insert into adicional_solicitudes (obra_id, motivo) values (p_obra_id, btrim(p_motivo)) returning id into v_id;
  insert into adicional_solicitud_partidas (solicitud_id, etapa, item_id, cantidad, pu)
  select v_id, x.etapa, x.item_id, x.cantidad, x.pu
    from jsonb_to_recordset(p_partidas) x(etapa text, item_id bigint, cantidad numeric, pu numeric);
  select count(*), sum(round(cantidad * pu, 2)) into v_n, v_total from adicional_solicitud_partidas where solicitud_id = v_id;

  perform notificar('GERENCIA', 'SOLICITUD_ADICIONAL',
    format('Adicional por aprobar en %s', v_obra.nombre),
    format('%s partida(s), %s · %s', v_n, fn_soles(v_total), btrim(p_motivo)),
    '/gerencia/adicionales');
  return v_id;
end;
$$;

-- Gerencia aprueba o rechaza una o varias (en el orden en que se pidieron: los N° de adicional salen en ese orden). Cada
-- una por separado: si una no se puede (otra persona ya la resolvió, la obra se cerró), las demás siguen; vuelve lo que
-- no se pudo y por qué. Dos gerentes a la vez: la segunda espera el bloqueo y la encuentra ya resuelta.
create or replace function public.resolver_adicionales(p_ids bigint[], p_aprobar boolean, p_respuesta text)
  returns jsonb language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_id bigint;
  s adicional_solicitudes%rowtype;
  v_req text;
  v_hechas int := 0;
  v_errores jsonb := '[]'::jsonb;
  v_obra text;
begin
  if rol_actual() not in ('GERENCIA', 'ADMIN') then
    raise exception 'Solo Gerencia aprueba los adicionales';
  end if;
  if not p_aprobar and btrim(coalesce(p_respuesta, '')) = '' then
    raise exception 'Escribe el motivo del rechazo';
  end if;
  if p_ids is null or cardinality(p_ids) = 0 then
    raise exception 'Elige al menos una solicitud';
  end if;

  for v_id in select a.id from adicional_solicitudes a where a.id = any (p_ids) order by a.solicitado_at, a.id loop
    begin
      select * into s from adicional_solicitudes where id = v_id for update;
      if s.estado <> 'PENDIENTE' then
        raise exception 'Ya fue %', lower(s.estado);
      end if;
      if p_aprobar then
        v_req := agregar_adicional(s.obra_id,
          (select jsonb_agg(jsonb_build_object('etapa', p.etapa, 'item_id', p.item_id, 'cantidad', p.cantidad, 'pu', p.pu) order by p.id)
             from adicional_solicitud_partidas p where p.solicitud_id = s.id));
        update adicional_solicitudes set estado = 'APROBADA', requerimiento = v_req, resuelto_by = auth.uid(), resuelto_at = now()
         where id = s.id;
      else
        update adicional_solicitudes set estado = 'RECHAZADA', respuesta = btrim(p_respuesta), resuelto_by = auth.uid(), resuelto_at = now()
         where id = s.id;
        select nombre into v_obra from obras where id = s.obra_id;
        perform notificar('LOGISTICA', 'ADICIONAL_RECHAZADO',
          format('Gerencia rechazó el adicional de %s', v_obra), btrim(p_respuesta), '/logistica/adicionales?estado=RECHAZADA');
      end if;
      v_hechas := v_hechas + 1;
    exception when others then
      v_errores := v_errores || jsonb_build_object('id', v_id, 'error', sqlerrm);
    end;
  end loop;
  return jsonb_build_object('hechas', v_hechas, 'errores', v_errores);
end;
$$;

revoke all on function public.pedir_adicional(bigint, jsonb, text) from public, anon;
revoke all on function public.resolver_adicionales(bigint[], boolean, text) from public, anon;
grant execute on function public.pedir_adicional(bigint, jsonb, text) to authenticated;
grant execute on function public.resolver_adicionales(bigint[], boolean, text) to authenticated;
