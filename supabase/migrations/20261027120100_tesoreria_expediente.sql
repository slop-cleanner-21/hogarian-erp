-- ============================================================ vistas
-- Parte de cada comprobante que corresponde a cada orden (base de v_por_pagar y pagar_documento).
--   factor       = parcial de las líneas de la orden en el comprobante / parcial de todas sus líneas
--                  (si el parcial total es 0: proporción de líneas)
--   neto_orden   = round(neto del comprobante * factor, 2)          (neto = total - retención)
--   pagado_orden = pagos al comprobante atribuidos a esta orden + factor * pagos no atribuidos.
--                  Un pago se atribuye a una orden si su VOUCHER (adjuntos) apunta a una orden de este
--                  comprobante (lo hace pagar_documento); los demás (registrar_pago directo, seed) se
--                  reparten en proporción.
--   saldo_orden  = max(0, min(saldo del comprobante, neto_orden - pagado_orden))
-- Con un comprobante de una sola orden (el caso normal) factor = 1 y saldo_orden = saldo del comprobante.
create view public.v_orden_comprobantes with (security_invoker = true) as
with lin as (
  select c.obra_id, c.numero_oc, c.comprobante_id,
         sum(coalesce(c.parcial, 0)) as parcial,
         count(*) as n
    from public.v_oc_items_calc c
   where c.comprobante_id is not null
   group by c.obra_id, c.numero_oc, c.comprobante_id
), f as (
  select l.*,
         case when sum(l.parcial) over w > 0 then l.parcial / sum(l.parcial) over w
              else l.n::numeric / sum(l.n) over w end as factor
    from lin l
  window w as (partition by l.comprobante_id)
), pa as (   -- pagos a comprobantes y la orden (del mismo comprobante) a la que se atribuyen
  select ap.comprobante_id, ap.monto, la.obra_id, la.numero_oc
    from public.pago_aplicaciones ap
    left join lateral (
      select a.obra_id, a.numero_oc
        from public.adjuntos a
       where a.pago_id = ap.pago_id and a.tipo = 'VOUCHER' and a.obra_id is not null
       order by a.id
       limit 1
    ) v on true
    left join lin la on la.comprobante_id = ap.comprobante_id and la.obra_id = v.obra_id and la.numero_oc = v.numero_oc
   where ap.comprobante_id is not null
), libre as (
  select pa.comprobante_id, sum(pa.monto) as monto from pa where pa.obra_id is null group by pa.comprobante_id
), atrib as (
  select pa.comprobante_id, pa.obra_id, pa.numero_oc, sum(pa.monto) as monto
    from pa where pa.obra_id is not null group by pa.comprobante_id, pa.obra_id, pa.numero_oc
), x as (
  select f.obra_id,
         f.numero_oc,
         f.comprobante_id,
         vc.fecha_emision,
         f.parcial,
         f.factor,
         vc.neto,
         vc.pagado,
         vc.saldo,
         round(vc.neto * f.factor, 2) as neto_orden,
         round(coalesce(at.monto, 0) + f.factor * coalesce(lb.monto, 0), 2) as pagado_orden
    from f
    join public.v_comprobantes vc on vc.id = f.comprobante_id
    left join libre lb on lb.comprobante_id = f.comprobante_id
    left join atrib at on at.comprobante_id = f.comprobante_id and at.obra_id = f.obra_id and at.numero_oc = f.numero_oc
)
select x.*,
       greatest(0, least(x.saldo, x.neto_orden - x.pagado_orden)) as saldo_orden
  from x;

-- ------------------------------------------------------------ v_por_pagar (Tesorería por documento)
-- OC/OS: montos en efectivo (netos de retención).
--   total  = Σ neto_orden de sus comprobantes + parcial de las líneas sin comprobante
--   saldo  = max(0, Σ saldo_orden + parcial sin comprobante - aplicaciones directas a la orden)
--   pagado = total - saldo
--   PENDIENTE: PRECIOS_CONFIRMADOS o FACTURADA con saldo > 0.005.
--   PAGADO:    PAGADA (o PRECIOS_CONFIRMADOS/FACTURADA con total > 0 y saldo ya cubierto).
-- OP: total = monto, pagado = Σ aplicaciones; PENDIENTE o PAGADA. Las ANULADA no aparecen.
create view public.v_por_pagar with (security_invoker = true) as
with lin as (
  select c.obra_id, c.numero_oc,
         coalesce(sum(coalesce(c.parcial, 0)) filter (where c.comprobante_id is null), 0) as sin_comp,
         bool_or(c.comprobante_id is null) as falta
    from public.v_oc_items_calc c
   group by c.obra_id, c.numero_oc
), cp as (
  select x.obra_id, x.numero_oc, count(*) as n, sum(x.neto_orden) as neto, sum(x.saldo_orden) as saldo
    from public.v_orden_comprobantes x
   group by x.obra_id, x.numero_oc
), dir as (
  select ap.obra_id, ap.numero_oc, sum(ap.monto) as pagado
    from public.pago_aplicaciones ap
   where ap.obra_id is not null
   group by ap.obra_id, ap.numero_oc
), ctr as (
  select distinct a.obra_id, a.numero_oc from public.adjuntos a where a.tipo = 'CONTRATO'
), ord as (
  select o.*,
         coalesce(cp.neto, 0) + coalesce(lin.sin_comp, 0) as total,
         greatest(0, coalesce(cp.saldo, 0) + coalesce(lin.sin_comp, 0) - coalesce(dir.pagado, 0)) as saldo,
         coalesce(cp.n, 0)::int as n_comprobantes,
         ctr.obra_id is not null as tiene_contrato,
         coalesce(lin.falta, false) as falta_comprobante
    from public.ordenes_compra o
    left join lin on lin.obra_id = o.obra_id and lin.numero_oc = o.numero
    left join cp on cp.obra_id = o.obra_id and cp.numero_oc = o.numero
    left join dir on dir.obra_id = o.obra_id and dir.numero_oc = o.numero
    left join ctr on ctr.obra_id = o.obra_id and ctr.numero_oc = o.numero
   where o.estado in ('PRECIOS_CONFIRMADOS', 'FACTURADA', 'PAGADA')
)
select o.tipo::text as doc,
       o.obra_id,
       o.numero,
       null::bigint as orden_pago_id,
       ob.empresa_id,
       e.nombre as empresa,
       ob.nombre as obra,
       o.proveedor_id,
       pr.razon_social as proveedor,
       pr.ruc_o_cod as ruc,
       pr.banco,
       pr.cuenta_bancaria,
       o.fecha,
       o.total,
       o.total - o.saldo as pagado,
       o.saldo,
       o.n_comprobantes,
       o.tiene_contrato,
       o.falta_comprobante,
       case when o.estado <> 'PAGADA' and o.saldo > 0.005 then 'PENDIENTE' else 'PAGADO' end as estado
  from ord o
  join public.obras ob on ob.id = o.obra_id
  join public.empresas e on e.id = ob.empresa_id
  join public.proveedores pr on pr.id = o.proveedor_id
 where o.estado = 'PAGADA'
    or o.saldo > 0.005
    or o.total > 0.005
union all
select 'OP'::text,
       op.obra_id,
       op.numero,
       op.id,
       ob.empresa_id,
       e.nombre,
       ob.nombre,
       op.proveedor_id,
       pr.razon_social,
       pr.ruc_o_cod,
       pr.banco,
       pr.cuenta_bancaria,
       op.fecha,
       op.monto,
       coalesce(pa.pagado, 0),
       greatest(0, op.monto - coalesce(pa.pagado, 0)),
       0,
       false,
       false,
       case when op.estado = 'PAGADA' then 'PAGADO' else 'PENDIENTE' end
  from public.ordenes_pago op
  join public.obras ob on ob.id = op.obra_id
  join public.empresas e on e.id = ob.empresa_id
  join public.proveedores pr on pr.id = op.proveedor_id
  left join (
    select ap.orden_pago_id, sum(ap.monto) as pagado
      from public.pago_aplicaciones ap
     where ap.orden_pago_id is not null
     group by ap.orden_pago_id
  ) pa on pa.orden_pago_id = op.id
 where op.estado in ('PENDIENTE', 'PAGADA');

-- ------------------------------------------------------------ v_expediente (una fila por comprobante)
-- Documentos: comprobante (archivo), orden, guía, voucher, fotos y contrato (solo si alguna orden es OS).
create view public.v_expediente with (security_invoker = true) as
with ord as (
  select distinct l.comprobante_id, l.obra_id, l.numero_oc, o.tipo
    from public.oc_items l
    join public.ordenes_compra o on o.obra_id = l.obra_id and o.numero = l.numero_oc
   where l.comprobante_id is not null
), oa as (
  select d.comprobante_id,
         string_agg(distinct d.tipo::text || ' ' || d.numero_oc, ', '
                    order by d.tipo::text || ' ' || d.numero_oc) as ordenes,
         (array_agg(d.obra_id order by d.obra_id, d.numero_oc))[1] as obra_id,
         (array_agg(d.numero_oc order by d.obra_id, d.numero_oc))[1] as numero_oc,
         bool_or(d.tipo = 'OS') as requiere_contrato
    from ord d
   group by d.comprobante_id
), adj as (
  select d.comprobante_id,
         bool_or(a.tipo = 'GUIA') as guia,
         bool_or(a.tipo = 'FOTO') as fotos,
         bool_or(a.tipo = 'CONTRATO') as contrato
    from ord d
    join public.adjuntos a on a.obra_id = d.obra_id and a.numero_oc = d.numero_oc
   where a.tipo in ('GUIA', 'FOTO', 'CONTRATO')
   group by d.comprobante_id
), vou as (
  select ap.comprobante_id
    from public.pago_aplicaciones ap
    join public.adjuntos a on a.pago_id = ap.pago_id and a.tipo = 'VOUCHER'
   where ap.comprobante_id is not null
  union
  select d.comprobante_id
    from ord d
    join public.pago_aplicaciones ap on ap.obra_id = d.obra_id and ap.numero_oc = d.numero_oc
    join public.adjuntos a on a.pago_id = ap.pago_id and a.tipo = 'VOUCHER'
), x as (
  select c.id as comprobante_id,
         c.empresa_id,
         c.periodo_anotacion::text as periodo,
         pr.razon_social as proveedor,
         c.serie,
         c.numero,
         c.tipo,
         oa.ordenes,
         oa.obra_id,
         oa.numero_oc,
         c.archivo_path is not null as tiene_archivo,
         oa.comprobante_id is not null as tiene_orden,
         coalesce(adj.guia, false) as tiene_guia,
         vou.comprobante_id is not null as tiene_voucher,
         coalesce(adj.fotos, false) as tiene_fotos,
         coalesce(oa.requiere_contrato, false) as requiere_contrato,
         coalesce(adj.contrato, false) as tiene_contrato
    from public.comprobantes c
    join public.proveedores pr on pr.id = c.proveedor_id
    left join oa on oa.comprobante_id = c.id
    left join adj on adj.comprobante_id = c.id
    left join vou on vou.comprobante_id = c.id
)
select x.*,
       (x.tiene_archivo::int + x.tiene_orden::int + x.tiene_guia::int + x.tiene_voucher::int
        + x.tiene_fotos::int + (x.requiere_contrato and x.tiene_contrato)::int) as docs_ok,
       5 + x.requiere_contrato::int as docs_req
  from x;

-- ------------------------------------------------------------ v_registro_compras (periodo = anotación)
-- estado_ple (PLE 8.1): '0' sin crédito fiscal (todo lo que no es FACTURA), '1' FACTURA anotada en su
-- mes de emisión, '6' FACTURA anotada en un periodo posterior. cuo: id del asiento, o 'C<id>' si no está contabilizado.
drop view public.v_registro_compras;
create view public.v_registro_compras with (security_invoker = true) as
select vc.empresa_id,
       vc.empresa,
       vc.empresa_ruc,
       c.periodo_anotacion::text as periodo,
       vc.id as comprobante_id,
       vc.tipo,
       vc.serie,
       vc.numero,
       vc.fecha_emision,
       vc.proveedor_id,
       vc.proveedor_ruc,
       vc.proveedor,
       vc.base,
       vc.igv,
       vc.total,
       vc.retencion,
       vc.asiento_id,
       coalesce(s.n, 0) as items_sin_cuenta,
       to_char(vc.fecha_emision, 'YYYYMM') as periodo_emision,
       coalesce(vc.asiento_id::text, 'C' || vc.id) as cuo,
       case when vc.tipo <> 'FACTURA' then '0'
            when c.periodo_anotacion::text > to_char(vc.fecha_emision, 'YYYYMM') then '6'
            else '1' end as estado_ple
  from public.v_comprobantes vc
  join public.comprobantes c on c.id = vc.id
  left join lateral (
    select count(distinct ci.item_id) as n
      from public.v_oc_items_calc ci
     where ci.comprobante_id = vc.id
       and ci.cuenta_contable is null
  ) s on true;

revoke all on public.v_orden_comprobantes, public.v_por_pagar, public.v_expediente, public.v_registro_compras from anon;
grant select on public.v_orden_comprobantes, public.v_por_pagar, public.v_expediente, public.v_registro_compras
  to authenticated, service_role;

-- ============================================================ RPC: órdenes de pago
create or replace function public.crear_orden_pago(
  p_obra_id bigint,
  p_proveedor_id bigint,
  p_concepto text,
  p_monto numeric,
  p_fecha date,
  p_cuenta text   -- null = se asigna después (obligatoria para contabilizar el pago)
)
returns text
language plpgsql
set search_path = public
as $$
declare
  v_cuenta text := nullif(btrim(p_cuenta), '');
  v_monto numeric := round(p_monto, 2);
  v_n int;
  v_numero text;
begin
  if not exists (select 1 from obras where id = p_obra_id) then
    raise exception 'La obra % no existe', p_obra_id;
  end if;
  if not exists (select 1 from proveedores where id = p_proveedor_id) then
    raise exception 'El beneficiario % no existe', p_proveedor_id;
  end if;
  if nullif(btrim(p_concepto), '') is null then
    raise exception 'Debe indicar el concepto de la orden de pago';
  end if;
  if v_monto is null or v_monto <= 0 then
    raise exception 'El monto de la orden de pago debe ser mayor que cero';
  end if;
  if v_cuenta is not null and not exists (select 1 from cuentas_contables where codigo = v_cuenta) then
    raise exception 'La cuenta contable % no existe', v_cuenta;
  end if;

  -- correlativo por obra (serializado por obra)
  perform pg_advisory_xact_lock(hashtextextended('ordenes_pago:' || p_obra_id, 0));
  select coalesce(max(substring(numero from '^OP-(\d+)$')::int), 0) + 1 into v_n
    from ordenes_pago where obra_id = p_obra_id;
  v_numero := 'OP-' || case when v_n < 10000 then lpad(v_n::text, 4, '0') else v_n::text end;

  insert into ordenes_pago (obra_id, numero, proveedor_id, concepto, monto, fecha, cuenta_contable)
  values (p_obra_id, v_numero, p_proveedor_id, btrim(p_concepto), v_monto, coalesce(p_fecha, current_date), v_cuenta);
  return v_numero;
end;
$$;

create or replace function public.anular_orden_pago(p_id bigint, p_motivo text)
returns void
language plpgsql
set search_path = public
as $$
declare
  v_op ordenes_pago%rowtype;
begin
  select * into v_op from ordenes_pago where id = p_id for update;
  if not found then
    raise exception 'La orden de pago % no existe', p_id;
  end if;
  if v_op.estado <> 'PENDIENTE' then
    raise exception 'Solo se pueden anular órdenes de pago PENDIENTES (la % está %)', v_op.numero, v_op.estado;
  end if;
  if nullif(btrim(p_motivo), '') is null then
    raise exception 'Debe indicar el motivo de anulación';
  end if;
  if exists (select 1 from pago_aplicaciones where orden_pago_id = p_id) then
    raise exception 'No se puede anular la orden de pago %: tiene pagos registrados', v_op.numero;
  end if;
  update ordenes_pago set estado = 'ANULADA', motivo_anulacion = btrim(p_motivo) where id = p_id;
end;
$$;

-- ============================================================ RPC: pagos
create or replace function public.registrar_pago(
  p_empresa_id bigint,
  p_fecha date,
  p_banco text,
  p_numero_operacion text,
  p_aplicaciones jsonb   -- [{comprobante_id, monto} | {obra_id, numero_oc, monto} | {orden_pago_id, monto}]
)
returns bigint
language plpgsql
set search_path = public
as $$
declare
  r record;
  v_emp bigint;
  v_estado estado_oc;
  v_op_estado text;
  v_op_numero text;
  v_saldo numeric;
  v_total numeric := 0;
  v_id bigint;
  v_aplic jsonb;
begin
  if not exists (select 1 from empresas where id = p_empresa_id) then
    raise exception 'La empresa % no existe', p_empresa_id;
  end if;
  if p_fecha is null then
    raise exception 'Debe indicar la fecha del pago';
  end if;
  if p_aplicaciones is null or jsonb_typeof(p_aplicaciones) <> 'array' or jsonb_array_length(p_aplicaciones) = 0 then
    raise exception 'El pago debe tener al menos una aplicación';
  end if;
  if exists (select 1 from jsonb_to_recordset(p_aplicaciones)
                           x(comprobante_id bigint, obra_id bigint, numero_oc text, orden_pago_id bigint, monto numeric)
              where x.monto is null or x.monto <= 0) then
    raise exception 'Cada aplicación requiere un monto mayor que cero';
  end if;
  if exists (select 1 from jsonb_to_recordset(p_aplicaciones)
                           x(comprobante_id bigint, obra_id bigint, numero_oc text, orden_pago_id bigint, monto numeric)
              where not ((x.comprobante_id is not null and x.obra_id is null and x.numero_oc is null and x.orden_pago_id is null)
                      or (x.comprobante_id is null and x.obra_id is not null and x.numero_oc is not null and x.orden_pago_id is null)
                      or (x.comprobante_id is null and x.obra_id is null and x.numero_oc is null and x.orden_pago_id is not null))) then
    raise exception 'Cada aplicación debe indicar un solo destino: comprobante_id, obra_id y numero_oc, u orden_pago_id';
  end if;

  -- agrupa por destino (comprobante, orden u orden de pago)
  select jsonb_agg(jsonb_build_object('comprobante_id', g.comprobante_id, 'obra_id', g.obra_id,
                                      'numero_oc', g.numero_oc, 'orden_pago_id', g.orden_pago_id, 'monto', g.monto))
    into v_aplic
    from (select x.comprobante_id, x.obra_id, x.numero_oc, x.orden_pago_id, sum(x.monto) as monto
            from jsonb_to_recordset(p_aplicaciones)
                 x(comprobante_id bigint, obra_id bigint, numero_oc text, orden_pago_id bigint, monto numeric)
           group by 1, 2, 3, 4) g;

  for r in select * from jsonb_to_recordset(v_aplic)
                         x(comprobante_id bigint, obra_id bigint, numero_oc text, orden_pago_id bigint, monto numeric)
            order by x.comprobante_id nulls last, x.obra_id nulls last, x.numero_oc, x.orden_pago_id loop
    if r.comprobante_id is not null then
      select c.empresa_id,
             c.total - c.retencion - coalesce((select sum(ap.monto) from pago_aplicaciones ap where ap.comprobante_id = c.id), 0)
        into v_emp, v_saldo
        from comprobantes c where c.id = r.comprobante_id for update;
      if not found then
        raise exception 'El comprobante % no existe', r.comprobante_id;
      end if;
      if v_emp <> p_empresa_id then
        raise exception 'El comprobante % pertenece a otra empresa', r.comprobante_id;
      end if;
      if r.monto > v_saldo + 0.005 then
        raise exception 'El monto % excede el saldo pendiente (%) del comprobante %', r.monto, v_saldo, r.comprobante_id;
      end if;
    elsif r.orden_pago_id is not null then
      select ob.empresa_id, op.estado, op.numero,
             op.monto - coalesce((select sum(ap.monto) from pago_aplicaciones ap where ap.orden_pago_id = op.id), 0)
        into v_emp, v_op_estado, v_op_numero, v_saldo
        from ordenes_pago op join obras ob on ob.id = op.obra_id
       where op.id = r.orden_pago_id
         for update of op;
      if not found then
        raise exception 'La orden de pago % no existe', r.orden_pago_id;
      end if;
      if v_emp <> p_empresa_id then
        raise exception 'La orden de pago % pertenece a otra empresa', v_op_numero;
      end if;
      if v_op_estado <> 'PENDIENTE' then
        raise exception 'Solo se pueden pagar órdenes de pago PENDIENTES (la % está %)', v_op_numero, v_op_estado;
      end if;
      if r.monto > v_saldo + 0.005 then
        raise exception 'El monto % excede el saldo pendiente (%) de la orden de pago %', r.monto, v_saldo, v_op_numero;
      end if;
    else
      select ob.empresa_id, o.estado into v_emp, v_estado
        from ordenes_compra o join obras ob on ob.id = o.obra_id
       where o.obra_id = r.obra_id and o.numero = r.numero_oc
         for update of o;
      if not found then
        raise exception 'La orden % no existe en la obra %', r.numero_oc, r.obra_id;
      end if;
      if v_emp <> p_empresa_id then
        raise exception 'La orden % pertenece a otra empresa', r.numero_oc;
      end if;
      if v_estado not in ('PRECIOS_CONFIRMADOS', 'FACTURADA') then
        raise exception 'Solo se pueden pagar órdenes con precios confirmados (la orden % está %)', r.numero_oc, v_estado;
      end if;
      select total - pagado into v_saldo from v_ordenes where obra_id = r.obra_id and numero = r.numero_oc;
      if r.monto > v_saldo + 0.005 then
        raise exception 'El monto % excede el saldo pendiente (%) de la orden %', r.monto, v_saldo, r.numero_oc;
      end if;
    end if;
    v_total := v_total + r.monto;
  end loop;

  insert into pagos (empresa_id, fecha, banco, numero_operacion, monto)
  values (p_empresa_id, p_fecha, nullif(btrim(p_banco), ''), nullif(btrim(p_numero_operacion), ''), v_total)
  returning id into v_id;

  insert into pago_aplicaciones (pago_id, comprobante_id, obra_id, numero_oc, orden_pago_id, monto)
  select v_id, x.comprobante_id, x.obra_id, x.numero_oc, x.orden_pago_id, x.monto
    from jsonb_to_recordset(v_aplic)
         x(comprobante_id bigint, obra_id bigint, numero_oc text, orden_pago_id bigint, monto numeric);

  -- órdenes cubiertas al 100% -> PAGADA
  update ordenes_compra o set estado = 'PAGADA'
    from v_ordenes v
   where v.obra_id = o.obra_id and v.numero = o.numero
     and o.estado in ('PRECIOS_CONFIRMADOS', 'FACTURADA')
     and v.total > 0
     and v.pagado >= v.total - 0.005
     and (o.obra_id, o.numero) in (
           select ap.obra_id, ap.numero_oc from pago_aplicaciones ap where ap.pago_id = v_id and ap.obra_id is not null
           union
           select l.obra_id, l.numero_oc from oc_items l
             join pago_aplicaciones ap on ap.comprobante_id = l.comprobante_id
            where ap.pago_id = v_id);

  -- órdenes de pago cubiertas al 100% -> PAGADA
  update ordenes_pago op set estado = 'PAGADA'
   where op.estado = 'PENDIENTE'
     and op.id in (select ap.orden_pago_id from pago_aplicaciones ap where ap.pago_id = v_id and ap.orden_pago_id is not null)
     and (select sum(ap.monto) from pago_aplicaciones ap where ap.orden_pago_id = op.id) >= op.monto - 0.005;
  return v_id;
end;
$$;

-- «Aprobar pago» de un solo paso, por documento: OC/OS (p_obra_id + p_numero) u OP (p_orden_pago_id).
-- OC/OS: el monto se aplica primero al saldo_orden de sus comprobantes (v_orden_comprobantes: parte de
-- cada comprobante que corresponde a la orden, neta de retención y de lo ya pagado), del más antiguo al
-- más reciente, y el resto como pago directo a la orden (cubre las líneas sin comprobante). El máximo
-- es el saldo de v_por_pagar. Delega en registrar_pago y registra el voucher en adjuntos.
create or replace function public.pagar_documento(
  p_obra_id bigint,
  p_numero text,
  p_orden_pago_id bigint,
  p_fecha date,
  p_banco text,
  p_numero_operacion text,
  p_monto numeric,
  p_voucher_path text,
  p_voucher_nombre text
)
returns bigint
language plpgsql
set search_path = public
as $$
declare
  v_path text := nullif(btrim(p_voucher_path), '');
  v_numero text := nullif(btrim(p_numero), '');
  v_monto numeric := round(p_monto, 2);
  v_emp bigint;
  v_estado estado_oc;
  v_op ordenes_pago%rowtype;
  v_aplic jsonb := '[]'::jsonb;
  v_saldo numeric;
  v_rest numeric;
  v_a numeric;
  v_pago bigint;
  v_ext text;
  r record;
begin
  if nullif(btrim(p_numero_operacion), '') is null then
    raise exception 'Debe indicar el N° de operación';
  end if;
  if v_path is null then
    raise exception 'Debe adjuntar el voucher del pago';
  end if;
  if exists (select 1 from adjuntos where path = v_path) then
    raise exception 'El archivo % ya está registrado', v_path;
  end if;
  if v_monto is null or v_monto <= 0 then
    raise exception 'El monto del pago debe ser mayor que cero';
  end if;
  if not ((p_orden_pago_id is not null and p_obra_id is null and v_numero is null)
       or (p_orden_pago_id is null and p_obra_id is not null and v_numero is not null)) then
    raise exception 'Indique la orden (obra y número) o la orden de pago, solo una de ellas';
  end if;

  if p_orden_pago_id is not null then
    select * into v_op from ordenes_pago where id = p_orden_pago_id for update;
    if not found then
      raise exception 'La orden de pago % no existe', p_orden_pago_id;
    end if;
    select empresa_id into v_emp from obras where id = v_op.obra_id;
    v_aplic := jsonb_build_array(jsonb_build_object('orden_pago_id', v_op.id, 'monto', v_monto));
  else
    select ob.empresa_id, o.estado into v_emp, v_estado
      from ordenes_compra o join obras ob on ob.id = o.obra_id
     where o.obra_id = p_obra_id and o.numero = v_numero
       for update of o;
    if not found then
      raise exception 'La orden % no existe en la obra', v_numero;
    end if;
    if v_estado not in ('PRECIOS_CONFIRMADOS', 'FACTURADA') then
      raise exception 'La orden % no está pendiente de pago (estado %)', v_numero, v_estado;
    end if;

    select p.saldo into v_saldo from v_por_pagar p
     where p.doc in ('OC', 'OS') and p.obra_id = p_obra_id and p.numero = v_numero;
    v_saldo := coalesce(v_saldo, 0);
    if v_saldo <= 0.005 then
      raise exception 'La orden % no tiene saldo por pagar', v_numero;
    end if;
    if v_monto > v_saldo then
      raise exception 'El monto % excede el saldo por pagar (%) de la orden %', v_monto, v_saldo, v_numero;
    end if;

    v_rest := v_monto;
    for r in select comprobante_id, saldo_orden
               from v_orden_comprobantes
              where obra_id = p_obra_id and numero_oc = v_numero and saldo_orden > 0
              order by fecha_emision, comprobante_id loop
      exit when v_rest <= 0;
      v_a := least(v_rest, r.saldo_orden);
      v_aplic := v_aplic || jsonb_build_object('comprobante_id', r.comprobante_id, 'monto', v_a);
      v_rest := v_rest - v_a;
    end loop;
    if v_rest > 0 then   -- resto <= líneas sin comprobante - pagos directos (por el tope de v_por_pagar)
      v_aplic := v_aplic || jsonb_build_object('obra_id', p_obra_id, 'numero_oc', v_numero, 'monto', v_rest);
    end if;
  end if;

  v_pago := registrar_pago(v_emp, p_fecha, p_banco, p_numero_operacion, v_aplic);

  v_ext := lower(substring(v_path from '\.([A-Za-z0-9]+)$'));
  insert into adjuntos (tipo, obra_id, numero_oc, pago_id, orden_pago_id, path, nombre, mime)
  values ('VOUCHER',
          case when p_orden_pago_id is null then p_obra_id end,
          case when p_orden_pago_id is null then v_numero end,
          v_pago,
          p_orden_pago_id,
          v_path,
          coalesce(nullif(btrim(p_voucher_nombre), ''), regexp_replace(v_path, '^.*/', '')),
          case v_ext when 'pdf' then 'application/pdf' when 'jpg' then 'image/jpeg' when 'jpeg' then 'image/jpeg'
                     when 'png' then 'image/png' when 'webp' then 'image/webp' when 'heic' then 'image/heic' end);

  -- con el voucher ya registrado (atribución del pago), la orden sin saldo pasa a PAGADA aunque un
  -- comprobante compartido con otra orden siga con saldo
  if p_orden_pago_id is null
     and (select p.saldo from v_por_pagar p
           where p.doc in ('OC', 'OS') and p.obra_id = p_obra_id and p.numero = v_numero) <= 0.005 then
    update ordenes_compra set estado = 'PAGADA'
     where obra_id = p_obra_id and numero = v_numero and estado in ('PRECIOS_CONFIRMADOS', 'FACTURADA');
  end if;
  return v_pago;
end;
$$;

-- ============================================================ RPC: contabilidad
create or replace function public.contabilizar_pago(p_pago_id bigint)
returns bigint
language plpgsql
set search_path = public
as $$
declare
  v_p pagos%rowtype;
  v_asiento bigint;
  v_sin text;
begin
  select * into v_p from pagos where id = p_pago_id for update;
  if not found then
    raise exception 'El pago % no existe', p_pago_id;
  end if;
  if exists (select 1 from asientos where pago_id = p_pago_id and origen = 'PAGO') then
    raise exception 'El pago % ya está contabilizado', p_pago_id;
  end if;
  select string_agg(op.numero, ', ' order by op.numero) into v_sin
    from pago_aplicaciones a join ordenes_pago op on op.id = a.orden_pago_id
   where a.pago_id = p_pago_id and op.cuenta_contable is null;
  if v_sin is not null then
    raise exception 'Asigne la cuenta contable de la OP % antes de contabilizar el pago', v_sin;
  end if;

  insert into asientos (empresa_id, fecha, glosa, origen, pago_id)
  values (v_p.empresa_id, v_p.fecha,
          format('Pago op. %s %s', coalesce(v_p.numero_operacion, 's/n'), coalesce(v_p.banco, '')), 'PAGO', v_p.id)
  returning id into v_asiento;

  -- Debe: cuenta de la OP; 4241 para RxH; 4212 para el resto y para pagos a órdenes sin comprobante
  insert into asiento_lineas (asiento_id, cuenta, debe)
  select v_asiento,
         case when a.orden_pago_id is not null then op.cuenta_contable
              when c.tipo = 'RXH' then '4241'
              else '4212' end,
         sum(a.monto)
    from pago_aplicaciones a
    left join comprobantes c on c.id = a.comprobante_id
    left join ordenes_pago op on op.id = a.orden_pago_id
   where a.pago_id = p_pago_id
   group by 2;
  insert into asiento_lineas (asiento_id, cuenta, haber) values (v_asiento, '1041', v_p.monto);

  if (select sum(debe) - sum(haber) from asiento_lineas where asiento_id = v_asiento) <> 0 then
    raise exception 'Asiento descuadrado para el pago %', p_pago_id;
  end if;
  return v_asiento;
end;
$$;

create or replace function public.actualizar_periodo_anotacion(p_comprobante_id bigint, p_periodo text)
returns void
language plpgsql
set search_path = public
as $$
declare
  v_c comprobantes%rowtype;
  v_per text := btrim(p_periodo);
begin
  select * into v_c from comprobantes where id = p_comprobante_id for update;
  if not found then
    raise exception 'El comprobante % no existe', p_comprobante_id;
  end if;
  if exists (select 1 from asientos where comprobante_id = p_comprobante_id and origen = 'COMPRA') then
    raise exception 'El comprobante %-% ya está contabilizado: no se puede cambiar el periodo', v_c.serie, v_c.numero;
  end if;
  if v_per is null or v_per !~ '^\d{4}(0[1-9]|1[0-2])$' then
    raise exception 'Periodo inválido: use el formato AAAAMM';
  end if;
  if v_per < to_char(v_c.fecha_emision, 'YYYYMM') then
    raise exception 'El periodo % es anterior al mes de emisión del comprobante (%)', v_per, to_char(v_c.fecha_emision, 'YYYYMM');
  end if;
  update comprobantes set periodo_anotacion = v_per where id = p_comprobante_id;
end;
$$;

