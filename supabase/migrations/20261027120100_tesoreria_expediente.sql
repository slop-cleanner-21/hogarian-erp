-- ============================================================ órdenes de pago (pagos sin OC/OS)
create table public.ordenes_pago (
  id               bigint generated by default as identity primary key,
  obra_id          bigint not null references public.obras (id),
  numero           text not null check (btrim(numero) <> ''),   -- OP-0001, correlativo por obra
  proveedor_id     bigint not null references public.proveedores (id),   -- beneficiario
  concepto         text not null check (btrim(concepto) <> ''),
  monto            numeric(14,2) not null check (monto > 0),
  fecha            date not null default current_date,
  cuenta_contable  text references public.cuentas_contables (codigo),
  estado           text not null default 'PENDIENTE' check (estado in ('PENDIENTE', 'PAGADA', 'ANULADA')),
  motivo_anulacion text,
  created_by       uuid default auth.uid(),
  created_at       timestamptz not null default now(),
  unique (obra_id, numero),
  check (estado <> 'ANULADA' or motivo_anulacion is not null)
);
create index ordenes_pago_proveedor_idx on public.ordenes_pago (proveedor_id);
create index ordenes_pago_estado_idx on public.ordenes_pago (estado);
create index ordenes_pago_cuenta_idx on public.ordenes_pago (cuenta_contable);

