create or replace function public.fn_comprobante_periodo()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.periodo_anotacion is null and new.fecha_emision is not null then
    new.periodo_anotacion := to_char(new.fecha_emision, 'YYYYMM');
  end if;
  return new;
end;
$$;

