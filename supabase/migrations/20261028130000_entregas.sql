-- Entregas: lo que llega de cada línea de la orden (material o servicio ejecutado), con fotos.
-- Las registran Logística y los residentes; el residente solo con la cámara de la app y con GPS.
-- Cuando lo entregado cubre lo pedido en todas las líneas, la orden pasa a RECIBIDA.

create table public.entregas (
  id           bigint generated by default as identity primary key,
  obra_id      bigint not null,
  numero_oc    text not null,
  oc_item_id   bigint not null references public.oc_items (id),
  cantidad     numeric(14,4) not null check (cantidad > 0),
  rol          text not null,
  lat          double precision,
  lng          double precision,
  precision_m  double precision,
  -- hora de la captura según el dispositivo; created_at es la hora del servidor
  capturado_en timestamptz,
  created_by   uuid not null default auth.uid() references auth.users (id),
  created_at   timestamptz not null default now(),
  foreign key (obra_id, numero_oc) references public.ordenes_compra (obra_id, numero),
  check ((lat is null) = (lng is null))
);
create index entregas_orden_idx on public.entregas (obra_id, numero_oc);
create index entregas_item_idx on public.entregas (oc_item_id);

create table public.entrega_fotos (
  id         bigint generated by default as identity primary key,
  entrega_id bigint not null references public.entregas (id) on delete cascade,
  path       text not null unique,
  created_at timestamptz not null default now()
);
create index entrega_fotos_entrega_idx on public.entrega_fotos (entrega_id);

alter table public.entregas enable row level security;
alter table public.entrega_fotos enable row level security;
-- Lectura para usuarios internos; las altas solo por registrar_entrega.
create policy entregas_select on public.entregas for select to authenticated using (true);
create policy entrega_fotos_select on public.entrega_fotos for select to authenticated using (true);
revoke all on public.entregas, public.entrega_fotos from anon;
grant select on public.entregas, public.entrega_fotos to authenticated;
grant all on public.entregas, public.entrega_fotos to service_role;

create trigger audit_entregas after insert or update or delete on public.entregas
  for each row execute function public.fn_audit();

-- Avance de cada línea de orden: pedido vs. entregado.
create view public.v_entregas_item with (security_invoker = true) as
select l.id as oc_item_id,
       l.obra_id,
       l.numero_oc,
       l.cantidad as pedido,
       coalesce(sum(e.cantidad), 0) as entregado
  from public.oc_items l
  left join public.entregas e on e.oc_item_id = l.id
 group by l.id;
grant select on public.v_entregas_item to authenticated;

-- Avance de cada partida del presupuesto: presupuestado, comprado (órdenes no anuladas) y llegado.
create view public.v_avance_partida with (security_invoker = true) as
select p.id as partida_id,
       p.obra_id,
       p.etapa,
       p.requerimiento,
       p.item_id,
       i.descripcion,
       i.unidad,
       i.rubro,
       p.cantidad as presupuestado,
       p.pu,
       round(p.cantidad * p.pu, 2) as parcial,
       coalesce(c.comprado, 0) as comprado,
       coalesce(c.monto_comprado, 0) as monto_comprado,
       coalesce(e.llegado, 0) as llegado,
       coalesce(e.fotos, 0) as fotos
  from public.partidas p
  join public.items i on i.id = p.item_id
  left join lateral (
    select sum(l.cantidad) as comprado, sum(coalesce(l.parcial, 0)) as monto_comprado
      from public.v_oc_items_calc l
     where l.partida_id = p.id and l.estado <> 'ANULADA'
  ) c on true
  left join lateral (
    select sum(en.cantidad) as llegado,
           (select count(*) from public.entrega_fotos f join public.entregas e2 on e2.id = f.entrega_id
              join public.oc_items l2 on l2.id = e2.oc_item_id where l2.partida_id = p.id) as fotos
      from public.entregas en
      join public.oc_items l on l.id = en.oc_item_id
     where l.partida_id = p.id
  ) e on true;
grant select on public.v_avance_partida to authenticated;

-- Registra una entrega con sus fotos (ya subidas al bucket "documentos").
create or replace function public.registrar_entrega(
  p_oc_item_id  bigint,
  p_cantidad    numeric,
  p_fotos       text[],
  p_lat         double precision default null,
  p_lng         double precision default null,
  p_precision   double precision default null,
  p_capturado   timestamptz default null
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_rol text := (select rol::text from perfiles where user_id = auth.uid());
  v_l oc_items%rowtype;
  v_estado estado_oc;
  v_entregado numeric;
  v_id bigint;
  f text;
begin
  if v_rol is null or v_rol not in ('LOGISTICA', 'RESIDENTE', 'ADMIN') then
    raise exception 'Solo Logística y los residentes registran entregas';
  end if;
  select * into v_l from oc_items where id = p_oc_item_id for update;
  if not found then
    raise exception 'La línea de la orden no existe';
  end if;
  select estado into v_estado from ordenes_compra where obra_id = v_l.obra_id and numero = v_l.numero_oc for update;
  if v_estado <> 'EN_ENTREGA' then
    raise exception 'La orden % no está en entrega (estado %)', v_l.numero_oc, v_estado;
  end if;
  if v_rol = 'RESIDENTE' then
    if v_l.obra_id not in (select obras_residente()) then
      raise exception 'La obra no está asignada a este residente';
    end if;
    if p_lat is null or p_lng is null then
      raise exception 'Activa la ubicación del teléfono para registrar la entrega';
    end if;
  end if;
  if p_cantidad is null or p_cantidad <= 0 then
    raise exception 'Ingresa la cantidad que llegó';
  end if;
  if p_fotos is null or cardinality(p_fotos) = 0 then
    raise exception 'Agrega al menos una foto';
  end if;
  select coalesce(sum(cantidad), 0) into v_entregado from entregas where oc_item_id = p_oc_item_id;
  if v_entregado + p_cantidad > v_l.cantidad + 0.0001 then
    raise exception 'Solo faltan % por llegar', v_l.cantidad - v_entregado;
  end if;

  insert into entregas (obra_id, numero_oc, oc_item_id, cantidad, rol, lat, lng, precision_m, capturado_en)
  values (v_l.obra_id, v_l.numero_oc, p_oc_item_id, p_cantidad, v_rol, p_lat, p_lng, p_precision, p_capturado)
  returning id into v_id;
  foreach f in array p_fotos loop
    if f is null or f !~ ('^entregas/' || v_l.obra_id || '/') then
      raise exception 'Ruta de foto inválida';
    end if;
    insert into entrega_fotos (entrega_id, path) values (v_id, f);
  end loop;

  -- Todo lo pedido llegó: la orden queda recibida.
  if not exists (
    select 1 from v_entregas_item where obra_id = v_l.obra_id and numero_oc = v_l.numero_oc and entregado < pedido - 0.0001
  ) then
    update ordenes_compra set estado = 'RECIBIDA' where obra_id = v_l.obra_id and numero = v_l.numero_oc;
  end if;
  return v_id;
end;
$$;
revoke execute on function public.registrar_entrega(bigint, numeric, text[], double precision, double precision, double precision, timestamptz) from public, anon;
grant execute on function public.registrar_entrega(bigint, numeric, text[], double precision, double precision, double precision, timestamptz) to authenticated, service_role;

-- Expediente: las fotos de las entregas también cuentan.
create or replace view public.v_expediente with (security_invoker = true) as
WITH ord AS (
         SELECT DISTINCT l.comprobante_id,
            l.obra_id,
            l.numero_oc,
            o.tipo
           FROM oc_items l
             JOIN ordenes_compra o ON o.obra_id = l.obra_id AND o.numero = l.numero_oc
          WHERE l.comprobante_id IS NOT NULL
        ), oa AS (
         SELECT d.comprobante_id,
            string_agg(DISTINCT (d.tipo::text || ' '::text) || d.numero_oc, ', '::text ORDER BY ((d.tipo::text || ' '::text) || d.numero_oc)) AS ordenes,
            (array_agg(d.obra_id ORDER BY d.obra_id, d.numero_oc))[1] AS obra_id,
            (array_agg(d.numero_oc ORDER BY d.obra_id, d.numero_oc))[1] AS numero_oc,
            bool_or(d.tipo = 'OS'::tipo_orden) AS requiere_contrato
           FROM ord d
          GROUP BY d.comprobante_id
        ), adj AS (
         SELECT d.comprobante_id,
            bool_or(a.tipo = 'GUIA'::tipo_adjunto) AS guia,
            bool_or(a.tipo = 'FOTO'::tipo_adjunto) AS fotos,
            bool_or(a.tipo = 'CONTRATO'::tipo_adjunto) AS contrato
           FROM ord d
             JOIN adjuntos a ON a.obra_id = d.obra_id AND a.numero_oc = d.numero_oc
          WHERE a.tipo = ANY (ARRAY['GUIA'::tipo_adjunto, 'FOTO'::tipo_adjunto, 'CONTRATO'::tipo_adjunto])
          GROUP BY d.comprobante_id
        ), vou AS (
         SELECT ap.comprobante_id
           FROM pago_aplicaciones ap
             JOIN adjuntos a ON a.pago_id = ap.pago_id AND a.tipo = 'VOUCHER'::tipo_adjunto
          WHERE ap.comprobante_id IS NOT NULL
        UNION
         SELECT d.comprobante_id
           FROM ord d
             JOIN pago_aplicaciones ap ON ap.obra_id = d.obra_id AND ap.numero_oc = d.numero_oc
             JOIN adjuntos a ON a.pago_id = ap.pago_id AND a.tipo = 'VOUCHER'::tipo_adjunto
        ), ef AS (
         SELECT DISTINCT d.comprobante_id
           FROM ord d
             JOIN entregas e ON e.obra_id = d.obra_id AND e.numero_oc = d.numero_oc
             JOIN entrega_fotos f ON f.entrega_id = e.id
        ), x AS (
         SELECT c.id AS comprobante_id,
            c.empresa_id,
            c.periodo_anotacion::text AS periodo,
            pr.razon_social AS proveedor,
            c.serie,
            c.numero,
            c.tipo,
            oa.ordenes,
            oa.obra_id,
            oa.numero_oc,
            c.archivo_path IS NOT NULL AS tiene_archivo,
            oa.comprobante_id IS NOT NULL AS tiene_orden,
            COALESCE(adj.guia, false) AS tiene_guia,
            vou.comprobante_id IS NOT NULL AS tiene_voucher,
            COALESCE(adj.fotos, false) OR ef.comprobante_id IS NOT NULL AS tiene_fotos,
            COALESCE(oa.requiere_contrato, false) AS requiere_contrato,
            COALESCE(adj.contrato, false) AS tiene_contrato
           FROM comprobantes c
             JOIN proveedores pr ON pr.id = c.proveedor_id
             LEFT JOIN oa ON oa.comprobante_id = c.id
             LEFT JOIN adj ON adj.comprobante_id = c.id
             LEFT JOIN vou ON vou.comprobante_id = c.id
             LEFT JOIN ef ON ef.comprobante_id = c.id
        )
 SELECT comprobante_id,
    empresa_id,
    periodo,
    proveedor,
    serie,
    numero,
    tipo,
    ordenes,
    obra_id,
    numero_oc,
    tiene_archivo,
    tiene_orden,
    tiene_guia,
    tiene_voucher,
    tiene_fotos,
    requiere_contrato,
    tiene_contrato,
    tiene_archivo::integer + tiene_orden::integer + tiene_voucher::integer + tiene_fotos::integer AS docs_ok,
    4 AS docs_req
   FROM x;;
