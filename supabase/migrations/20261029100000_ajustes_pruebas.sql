-- Ajustes tras las primeras pruebas con usuarios:
--   * Datos de demostración (archivos generados) registrados aparte, para la migración final.
--   * Cada usuario puede borrar sus avisos.
--   * Filtros por etapa y tipo de material en la bandeja de órdenes.
--   * El rol y el nombre viajan en el token (app_metadata): la app no consulta el perfil en cada pantalla.

-- ============================================================ datos de demostración
-- Archivos generados (comprobantes, vouchers) para que la demo tenga todo: se identifican aquí y se
-- quitarán cuando se migren los datos reales.
create table public.datos_demo (
  id          bigint generated by default as identity primary key,
  tabla       text not null,
  registro_id text not null,
  archivo     text,
  created_at  timestamptz not null default now(),
  unique (tabla, registro_id)
);
alter table public.datos_demo enable row level security;
create policy datos_demo_select on public.datos_demo for select to authenticated using (true);
revoke all on public.datos_demo from anon;
grant select on public.datos_demo to authenticated;
grant all on public.datos_demo to service_role;

-- ============================================================ avisos: borrar los propios
create policy notificaciones_delete on public.notificaciones for delete to authenticated
  using (user_id = (select auth.uid()));
grant delete on public.notificaciones to authenticated;

-- ============================================================ órdenes: etapas y tipos de material
create or replace view public.v_ordenes with (security_invoker = true) as
SELECT o.obra_id,
    o.numero,
    ob.nombre AS obra,
    ob.empresa_id,
    e.nombre AS empresa,
    e.ruc AS empresa_ruc,
    o.proveedor_id,
    pr.razon_social AS proveedor,
    pr.ruc_o_cod AS proveedor_ruc,
    o.tipo,
    o.fecha,
    o.estado,
    o.token_cotizacion,
    COALESCE(t.n_items, 0::bigint) AS n_items,
    COALESCE(t.total, 0::numeric) AS total,
    COALESCE(t.facturado, 0::numeric) AS facturado,
    round(COALESCE(t.pagado_cpe, 0::numeric) + COALESCE(d.pagado, 0::numeric), 2) AS pagado,
    COALESCE(t.has_alertas, false) AS has_alertas,
    o.created_at,
    o.motivo_anulacion,
    o.updated_at,
    ( SELECT array_agg(DISTINCT p.etapa) FROM oc_items l JOIN partidas p ON p.id = l.partida_id
          WHERE l.obra_id = o.obra_id AND l.numero_oc = o.numero) AS etapas,
    ( SELECT array_agg(DISTINCT i.tipo_material) FILTER (WHERE i.tipo_material IS NOT NULL)
           FROM oc_items l JOIN partidas p ON p.id = l.partida_id JOIN items i ON i.id = p.item_id
          WHERE l.obra_id = o.obra_id AND l.numero_oc = o.numero) AS tipos_material
   FROM ordenes_compra o
     JOIN obras ob ON ob.id = o.obra_id
     JOIN empresas e ON e.id = ob.empresa_id
     JOIN proveedores pr ON pr.id = o.proveedor_id
     LEFT JOIN LATERAL ( SELECT count(*) AS n_items,
            sum(COALESCE(c.parcial, 0::numeric)) AS total,
            sum(COALESCE(c.parcial, 0::numeric)) FILTER (WHERE c.comprobante_id IS NOT NULL) AS facturado,
            sum(COALESCE(c.parcial, 0::numeric) * COALESCE(f.factor, 0::numeric)) AS pagado_cpe,
            bool_or(c.sobreprecio) AS has_alertas
           FROM v_oc_items_calc c
             LEFT JOIN LATERAL ( SELECT
                        CASE
                            WHEN (cp.total - cp.retencion) > 0::numeric THEN LEAST(1::numeric, COALESCE(sum(ap.monto), 0::numeric) / (cp.total - cp.retencion))
                            ELSE 1::numeric
                        END AS factor
                   FROM comprobantes cp
                     LEFT JOIN pago_aplicaciones ap ON ap.comprobante_id = cp.id
                  WHERE cp.id = c.comprobante_id
                  GROUP BY cp.id) f ON true
          WHERE c.obra_id = o.obra_id AND c.numero_oc = o.numero) t ON true
     LEFT JOIN LATERAL ( SELECT sum(ap.monto) AS pagado
           FROM pago_aplicaciones ap
          WHERE ap.obra_id = o.obra_id AND ap.numero_oc = o.numero) d ON true;

-- ============================================================ rol y nombre en el token
-- Se copian a auth.users.raw_app_meta_data (solo los cambia el servidor) y quedan en el JWT.
create or replace function public.fn_perfil_a_token()
returns trigger
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
begin
  update auth.users
     set raw_app_meta_data = coalesce(raw_app_meta_data, '{}'::jsonb) || jsonb_build_object('rol', new.rol::text, 'nombre', new.nombre)
   where id = new.user_id;
  return new;
end;
$$;
create trigger perfiles_a_token after insert or update of rol, nombre on public.perfiles
  for each row execute function public.fn_perfil_a_token();

update auth.users u
   set raw_app_meta_data = coalesce(u.raw_app_meta_data, '{}'::jsonb) || jsonb_build_object('rol', p.rol::text, 'nombre', p.nombre)
  from public.perfiles p
 where p.user_id = u.id;
