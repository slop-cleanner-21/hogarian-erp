-- Proveedores: contactos (teléfono con WhatsApp/Telegram) y tipos de material que venden.
-- Guía de remisión: la sube quien recibe el material en obra (residente) o Logística.

-- ------------------------------------------------------------ contactos
create table public.proveedor_contactos (
  id           bigint generated by default as identity primary key,
  proveedor_id bigint not null references public.proveedores (id) on delete cascade,
  nombre       text,
  telefono     text not null check (btrim(telefono) <> ''),
  whatsapp     boolean not null default false,
  telegram     boolean not null default false,
  created_at   timestamptz not null default now()
);
create index proveedor_contactos_proveedor_idx on public.proveedor_contactos (proveedor_id);

-- ------------------------------------------------------------ tipos de material que vende
create table public.proveedor_tipos_material (
  proveedor_id  bigint not null references public.proveedores (id) on delete cascade,
  tipo_material text not null references public.tipos_material (codigo) on update cascade on delete cascade,
  primary key (proveedor_id, tipo_material)
);
create index proveedor_tipos_material_tipo_idx on public.proveedor_tipos_material (tipo_material);

alter table public.proveedor_contactos enable row level security;
alter table public.proveedor_tipos_material enable row level security;
create policy proveedor_contactos_authenticated_all on public.proveedor_contactos
  for all to authenticated using (true) with check (true);
create policy proveedor_tipos_material_authenticated_all on public.proveedor_tipos_material
  for all to authenticated using (true) with check (true);
revoke all on public.proveedor_contactos, public.proveedor_tipos_material from anon;
grant select, insert, update, delete on public.proveedor_contactos, public.proveedor_tipos_material
  to authenticated, service_role;
grant usage, select on sequence public.proveedor_contactos_id_seq to authenticated, service_role;

-- ------------------------------------------------------------ guía de remisión: también el residente
drop policy adjuntos_insert on public.adjuntos;
create policy adjuntos_insert on public.adjuntos for insert to authenticated
  with check (
    (not (select public.es_residente()))
    or (tipo in ('FOTO', 'GUIA') and obra_id in (select public.obras_residente()))
  );

drop policy adjuntos_delete on public.adjuntos;
create policy adjuntos_delete on public.adjuntos for delete to authenticated
  using (
    (not (select public.es_residente()))
    or (tipo in ('FOTO', 'GUIA') and created_by = auth.uid())
  );
