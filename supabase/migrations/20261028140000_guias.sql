-- Guía de remisión (solo OC). Logística decide si la orden la requiere y la pide con los datos del
-- traslado; Contabilidad la emite en SUNAT y sube el PDF. Transportistas: catálogo de Logística.

alter table public.ordenes_compra add column requiere_guia boolean not null default false;

create table public.transportistas (
  id           bigint generated by default as identity primary key,
  ruc          text not null unique check (ruc ~ '^\d{11}$'),
  razon_social text not null check (btrim(razon_social) <> ''),
  placa        text,
  licencia     text,
  created_at   timestamptz not null default now()
);
alter table public.transportistas enable row level security;
create policy transportistas_authenticated_all on public.transportistas for all to authenticated using (true) with check (true);
revoke all on public.transportistas from anon;
grant select, insert, update, delete on public.transportistas to authenticated;
grant all on public.transportistas to service_role;

create table public.guias (
  id                bigint generated by default as identity primary key,
  obra_id           bigint not null,
  numero_oc         text not null,
  estado            text not null default 'SOLICITADA'
                    check (estado in ('SOLICITADA', 'EMITIDA', 'ANULACION_PENDIENTE', 'ANULADA')),
  punto_partida     text not null,
  punto_llegada     text not null,
  ruc_remitente     text not null,
  transportista_id  bigint references public.transportistas (id),
  ruc_transportista text not null,
  transportista     text not null,
  placa             text not null,
  licencia          text not null,
  detalle           text not null,
  fecha_traslado    date not null,
  numero_guia       text,
  archivo_path      text,
  solicitado_by     uuid default auth.uid(),
  solicitado_at     timestamptz not null default now(),
  emitido_by        uuid,
  emitido_at        timestamptz,
  anulada_at        timestamptz,
  foreign key (obra_id, numero_oc) references public.ordenes_compra (obra_id, numero),
  check (estado = 'SOLICITADA' or estado = 'ANULADA' or (numero_guia is not null and archivo_path is not null))
);
-- Una guía vigente por orden (las anuladas quedan de historial).
create unique index guias_vigente_idx on public.guias (obra_id, numero_oc) where estado <> 'ANULADA';
create index guias_estado_idx on public.guias (estado);
alter table public.guias enable row level security;
create policy guias_select on public.guias for select to authenticated using (true);
revoke all on public.guias from anon;
grant select on public.guias to authenticated;
grant all on public.guias to service_role;
create trigger audit_guias after insert or update or delete on public.guias
  for each row execute function public.fn_audit();

-- ------------------------------------------------------------ Logística
-- Marca si la OC requiere guía; se puede retractar mientras la guía no esté emitida.
create or replace function public.set_requiere_guia(p_obra_id bigint, p_numero text, p_requiere boolean)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_o ordenes_compra%rowtype;
begin
  if coalesce((select rol::text from perfiles where user_id = auth.uid()), '') not in ('LOGISTICA', 'ADMIN') then
    raise exception 'Solo Logística decide si la orden lleva guía';
  end if;
  select * into v_o from ordenes_compra where obra_id = p_obra_id and numero = p_numero for update;
  if not found then
    raise exception 'La orden % no existe', p_numero;
  end if;
  if v_o.tipo <> 'OC' then
    raise exception 'Solo las órdenes de compra llevan guía de remisión';
  end if;
  if not p_requiere and exists (select 1 from guias where obra_id = p_obra_id and numero_oc = p_numero and estado in ('EMITIDA', 'ANULACION_PENDIENTE')) then
    raise exception 'La guía ya fue emitida: anula la orden o pide a Contabilidad que la anule';
  end if;
  update ordenes_compra set requiere_guia = p_requiere where obra_id = p_obra_id and numero = p_numero;
  if not p_requiere then
    update guias set estado = 'ANULADA', anulada_at = now()
     where obra_id = p_obra_id and numero_oc = p_numero and estado = 'SOLICITADA';
  end if;
end;
$$;

-- Pide (o corrige) la guía con los datos del traslado. Desde que la orden está cotizada.
create or replace function public.solicitar_guia(p_obra_id bigint, p_numero text, p_datos jsonb)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_o ordenes_compra%rowtype;
  v_t transportistas%rowtype;
  v_id bigint;
  v_nueva boolean;
begin
  if coalesce((select rol::text from perfiles where user_id = auth.uid()), '') not in ('LOGISTICA', 'ADMIN') then
    raise exception 'Solo Logística pide la guía';
  end if;
  select * into v_o from ordenes_compra where obra_id = p_obra_id and numero = p_numero for update;
  if not found or v_o.tipo <> 'OC' or not v_o.requiere_guia then
    raise exception 'La orden no requiere guía de remisión';
  end if;
  if v_o.estado in ('BORRADOR', 'EMITIDA', 'ANULADA') then
    raise exception 'La guía se pide con la orden cotizada (estado %)', v_o.estado;
  end if;
  select * into v_t from transportistas where id = (p_datos->>'transportista_id')::bigint;
  if not found then
    raise exception 'Elige el transportista';
  end if;
  if exists (select 1 from guias where obra_id = p_obra_id and numero_oc = p_numero and estado in ('EMITIDA', 'ANULACION_PENDIENTE')) then
    raise exception 'La guía ya fue emitida';
  end if;
  if nullif(btrim(p_datos->>'punto_partida'), '') is null or nullif(btrim(p_datos->>'punto_llegada'), '') is null
     or nullif(btrim(p_datos->>'placa'), '') is null or nullif(btrim(p_datos->>'licencia'), '') is null
     or nullif(btrim(p_datos->>'detalle'), '') is null or (p_datos->>'fecha_traslado') is null then
    raise exception 'Completa todos los datos de la guía';
  end if;

  select id into v_id from guias where obra_id = p_obra_id and numero_oc = p_numero and estado = 'SOLICITADA';
  v_nueva := v_id is null;
  if v_nueva then
    insert into guias (obra_id, numero_oc, punto_partida, punto_llegada, ruc_remitente, transportista_id, ruc_transportista,
                       transportista, placa, licencia, detalle, fecha_traslado)
    values (p_obra_id, p_numero, btrim(p_datos->>'punto_partida'), btrim(p_datos->>'punto_llegada'),
            (select ruc_o_cod from proveedores where id = v_o.proveedor_id), v_t.id, v_t.ruc, v_t.razon_social,
            upper(btrim(p_datos->>'placa')), upper(btrim(p_datos->>'licencia')), btrim(p_datos->>'detalle'),
            (p_datos->>'fecha_traslado')::date)
    returning id into v_id;
  else
    update guias set punto_partida = btrim(p_datos->>'punto_partida'), punto_llegada = btrim(p_datos->>'punto_llegada'),
                     transportista_id = v_t.id, ruc_transportista = v_t.ruc, transportista = v_t.razon_social,
                     placa = upper(btrim(p_datos->>'placa')), licencia = upper(btrim(p_datos->>'licencia')),
                     detalle = btrim(p_datos->>'detalle'), fecha_traslado = (p_datos->>'fecha_traslado')::date
     where id = v_id;
  end if;
  perform notificar('CONTABILIDAD', 'GUIA_SOLICITADA',
                    format(case when v_nueva then 'Guía solicitada: OC %s' else 'Guía corregida: OC %s' end, p_numero),
                    (select razon_social from proveedores where id = v_o.proveedor_id), '/contabilidad/guias');
  return v_id;
end;
$$;

-- ------------------------------------------------------------ Contabilidad
create or replace function public.emitir_guia(p_id bigint, p_numero_guia text, p_archivo_path text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if coalesce((select rol::text from perfiles where user_id = auth.uid()), '') not in ('CONTABILIDAD', 'ADMIN') then
    raise exception 'Solo Contabilidad emite la guía';
  end if;
  if nullif(btrim(p_numero_guia), '') is null or nullif(btrim(p_archivo_path), '') is null then
    raise exception 'Ingresa el N° de guía y sube el PDF';
  end if;
  update guias set estado = 'EMITIDA', numero_guia = upper(btrim(p_numero_guia)), archivo_path = p_archivo_path,
                   emitido_by = auth.uid(), emitido_at = now()
   where id = p_id and estado = 'SOLICITADA';
  if not found then
    raise exception 'La guía no está pendiente de emisión';
  end if;
end;
$$;

create or replace function public.marcar_guia_anulada(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if coalesce((select rol::text from perfiles where user_id = auth.uid()), '') not in ('CONTABILIDAD', 'ADMIN') then
    raise exception 'Solo Contabilidad anula la guía';
  end if;
  update guias set estado = 'ANULADA', anulada_at = now() where id = p_id and estado = 'ANULACION_PENDIENTE';
  if not found then
    raise exception 'La guía no está pendiente de anulación';
  end if;
end;
$$;

revoke execute on function public.set_requiere_guia(bigint, text, boolean), public.solicitar_guia(bigint, text, jsonb),
  public.emitir_guia(bigint, text, text), public.marcar_guia_anulada(bigint) from public, anon;
grant execute on function public.set_requiere_guia(bigint, text, boolean), public.solicitar_guia(bigint, text, jsonb),
  public.emitir_guia(bigint, text, text), public.marcar_guia_anulada(bigint) to authenticated, service_role;

-- ------------------------------------------------------------ anular OC: también la guía
CREATE OR REPLACE FUNCTION public.anular_orden(p_obra_id bigint, p_numero text, p_motivo text)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public'
SECURITY DEFINER
AS $function$
declare
  v_estado estado_oc;
begin
  select estado into v_estado from ordenes_compra
   where obra_id = p_obra_id and numero = p_numero for update;
  if not found then
    raise exception 'La orden % no existe en la obra', p_numero;
  end if;
  if v_estado = 'ANULADA' then
    raise exception 'La orden % ya está anulada', p_numero;
  end if;
  if nullif(btrim(p_motivo), '') is null then
    raise exception 'Debe indicar el motivo de anulación';
  end if;
  if exists (select 1 from oc_items where obra_id = p_obra_id and numero_oc = p_numero and comprobante_id is not null) then
    raise exception 'No se puede anular la orden %: tiene comprobantes registrados', p_numero;
  end if;
  if exists (select 1 from pago_aplicaciones where obra_id = p_obra_id and numero_oc = p_numero) then
    raise exception 'No se puede anular la orden %: tiene pagos registrados', p_numero;
  end if;
  update ordenes_compra set estado = 'ANULADA', motivo_anulacion = btrim(p_motivo)
   where obra_id = p_obra_id and numero = p_numero;

  -- Guía: si ya se emitió en SUNAT, Contabilidad debe anularla allá; si solo estaba pedida, se cancela.
  update guias set estado = 'ANULACION_PENDIENTE'
   where obra_id = p_obra_id and numero_oc = p_numero and estado = 'EMITIDA';
  if found then
    perform notificar('CONTABILIDAD', 'GUIA_ANULAR', format('Anular en SUNAT la guía de la OC %s', p_numero),
                      'La orden de compra fue anulada', '/contabilidad/guias?est=anu');
  end if;
  update guias set estado = 'ANULADA', anulada_at = now()
   where obra_id = p_obra_id and numero_oc = p_numero and estado = 'SOLICITADA';
end;
$function$;

-- Expediente: la guía emitida cuenta.
create or replace view public.v_expediente with (security_invoker = true) as
WITH ord AS (
         SELECT DISTINCT l.comprobante_id,
            l.obra_id,
            l.numero_oc,
            o.tipo
           FROM oc_items l
             JOIN ordenes_compra o ON o.obra_id = l.obra_id AND o.numero = l.numero_oc
          WHERE l.comprobante_id IS NOT NULL
        ), oa AS (
         SELECT d.comprobante_id,
            string_agg(DISTINCT (d.tipo::text || ' '::text) || d.numero_oc, ', '::text ORDER BY ((d.tipo::text || ' '::text) || d.numero_oc)) AS ordenes,
            (array_agg(d.obra_id ORDER BY d.obra_id, d.numero_oc))[1] AS obra_id,
            (array_agg(d.numero_oc ORDER BY d.obra_id, d.numero_oc))[1] AS numero_oc,
            bool_or(d.tipo = 'OS'::tipo_orden) AS requiere_contrato
           FROM ord d
          GROUP BY d.comprobante_id
        ), adj AS (
         SELECT d.comprobante_id,
            bool_or(a.tipo = 'GUIA'::tipo_adjunto) AS guia,
            bool_or(a.tipo = 'FOTO'::tipo_adjunto) AS fotos,
            bool_or(a.tipo = 'CONTRATO'::tipo_adjunto) AS contrato
           FROM ord d
             JOIN adjuntos a ON a.obra_id = d.obra_id AND a.numero_oc = d.numero_oc
          WHERE a.tipo = ANY (ARRAY['GUIA'::tipo_adjunto, 'FOTO'::tipo_adjunto, 'CONTRATO'::tipo_adjunto])
          GROUP BY d.comprobante_id
        ), vou AS (
         SELECT ap.comprobante_id
           FROM pago_aplicaciones ap
             JOIN adjuntos a ON a.pago_id = ap.pago_id AND a.tipo = 'VOUCHER'::tipo_adjunto
          WHERE ap.comprobante_id IS NOT NULL
        UNION
         SELECT d.comprobante_id
           FROM ord d
             JOIN pago_aplicaciones ap ON ap.obra_id = d.obra_id AND ap.numero_oc = d.numero_oc
             JOIN adjuntos a ON a.pago_id = ap.pago_id AND a.tipo = 'VOUCHER'::tipo_adjunto
        ), gu AS (
         SELECT DISTINCT d.comprobante_id
           FROM ord d
             JOIN guias g ON g.obra_id = d.obra_id AND g.numero_oc = d.numero_oc AND g.estado = 'EMITIDA'
        ), ef AS (
         SELECT DISTINCT d.comprobante_id
           FROM ord d
             JOIN entregas e ON e.obra_id = d.obra_id AND e.numero_oc = d.numero_oc
             JOIN entrega_fotos f ON f.entrega_id = e.id
        ), x AS (
         SELECT c.id AS comprobante_id,
            c.empresa_id,
            c.periodo_anotacion::text AS periodo,
            pr.razon_social AS proveedor,
            c.serie,
            c.numero,
            c.tipo,
            oa.ordenes,
            oa.obra_id,
            oa.numero_oc,
            c.archivo_path IS NOT NULL AS tiene_archivo,
            oa.comprobante_id IS NOT NULL AS tiene_orden,
            COALESCE(adj.guia, false) OR gu.comprobante_id IS NOT NULL AS tiene_guia,
            vou.comprobante_id IS NOT NULL AS tiene_voucher,
            COALESCE(adj.fotos, false) OR ef.comprobante_id IS NOT NULL AS tiene_fotos,
            COALESCE(oa.requiere_contrato, false) AS requiere_contrato,
            COALESCE(adj.contrato, false) AS tiene_contrato
           FROM comprobantes c
             JOIN proveedores pr ON pr.id = c.proveedor_id
             LEFT JOIN oa ON oa.comprobante_id = c.id
             LEFT JOIN adj ON adj.comprobante_id = c.id
             LEFT JOIN vou ON vou.comprobante_id = c.id
             LEFT JOIN ef ON ef.comprobante_id = c.id
             LEFT JOIN gu ON gu.comprobante_id = c.id
        )
 SELECT comprobante_id,
    empresa_id,
    periodo,
    proveedor,
    serie,
    numero,
    tipo,
    ordenes,
    obra_id,
    numero_oc,
    tiene_archivo,
    tiene_orden,
    tiene_guia,
    tiene_voucher,
    tiene_fotos,
    requiere_contrato,
    tiene_contrato,
    tiene_archivo::integer + tiene_orden::integer + tiene_voucher::integer + tiene_fotos::integer AS docs_ok,
    4 AS docs_req
   FROM x;;
