-- Link de cotización: ciclo de vida, vencimiento, token único vigente, registro de accesos y
-- límite de intentos. Además, tablas de órdenes en la publicación de Realtime.

-- ============================================================ estado de la cotización
create type public.cotizacion_estado as enum ('SIN_ENVIAR', 'ENVIADA', 'RECIBIDA');

alter table public.ordenes_compra
  add column cotizacion_estado      public.cotizacion_estado not null default 'SIN_ENVIAR',
  add column cotizacion_enviada_at  timestamptz,
  add column cotizacion_recibida_at timestamptz,
  alter column token_cotizacion drop not null;

-- Al salir de "Cotizando" (precios confirmados, anulada…) el link vence: sin token no hay acceso.
create or replace function public.fn_vencer_cotizacion()
returns trigger
language plpgsql
as $$
begin
  if old.estado = 'EMITIDA' and new.estado <> 'EMITIDA' then
    new.token_cotizacion := null;
  end if;
  return new;
end;
$$;

create trigger ordenes_compra_vencer_cotizacion before update of estado on public.ordenes_compra
  for each row execute function public.fn_vencer_cotizacion();

-- Datos existentes: solo las órdenes en cotización conservan su link.
set app.skip_audit = 'on';
update public.ordenes_compra set token_cotizacion = null where estado <> 'EMITIDA';
reset app.skip_audit;

-- ============================================================ registro de accesos
create table public.cotizacion_accesos (
  id         bigint generated by default as identity primary key,
  token      uuid,
  obra_id    bigint,
  numero     text,
  accion     text not null check (accion in ('VER', 'ENVIAR')),
  ok         boolean not null,
  created_at timestamptz not null default now()
);
create index cotizacion_accesos_token_idx on public.cotizacion_accesos (token, created_at desc);
create index cotizacion_accesos_orden_idx on public.cotizacion_accesos (obra_id, numero);
create index cotizacion_accesos_fallidos_idx on public.cotizacion_accesos (created_at) where not ok;

alter table public.cotizacion_accesos enable row level security;
-- Solo lectura para usuarios internos; se escribe únicamente desde las funciones del link.
create policy cotizacion_accesos_select on public.cotizacion_accesos for select to authenticated using (true);
revoke all on public.cotizacion_accesos from anon;
grant select on public.cotizacion_accesos to authenticated;

-- Límites: por token (abrir/enviar en bucle) y global de tokens inválidos (búsqueda a ciegas).
create or replace function public.fn_cotizacion_limite(p_token uuid)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if (select count(*) from cotizacion_accesos where token = p_token and created_at > now() - interval '10 minutes') >= 120 then
    raise exception 'Demasiados intentos. Vuelve a intentarlo en unos minutos.' using errcode = 'P0429';
  end if;
  if (select count(*) from cotizacion_accesos where not ok and created_at > now() - interval '1 minute') >= 60 then
    raise exception 'Demasiados intentos. Vuelve a intentarlo en unos minutos.' using errcode = 'P0429';
  end if;
end;
$$;

-- ============================================================ lectura pública (anon, por token)
-- Devuelve solo lo necesario para cotizar. Un link vencido o inexistente no lanza error: responde
-- {disponible: false} para que el intento fallido quede registrado (y cuente para el límite).
drop function public.get_cotizacion(uuid);
create function public.get_cotizacion(p_token uuid)
returns jsonb
language plpgsql
volatile
security definer
set search_path = public, pg_temp
as $$
declare
  v_o ordenes_compra%rowtype;
  v jsonb;
begin
  perform fn_cotizacion_limite(p_token);
  select * into v_o from ordenes_compra where token_cotizacion = p_token;
  if not found or v_o.estado <> 'EMITIDA' or v_o.cotizacion_estado = 'SIN_ENVIAR' then
    insert into cotizacion_accesos (token, accion, ok) values (p_token, 'VER', false);
    return jsonb_build_object('disponible', false);
  end if;
  insert into cotizacion_accesos (token, obra_id, numero, accion, ok) values (p_token, v_o.obra_id, v_o.numero, 'VER', true);

  select jsonb_build_object(
           'disponible', true,
           'numero', v_o.numero,
           'tipo', v_o.tipo,
           'obra', ob.nombre,
           'empresa', e.nombre,
           'empresa_ruc', e.ruc,
           'proveedor', pr.razon_social,
           'fecha', v_o.fecha,
           'cotizacion_estado', v_o.cotizacion_estado,
           'items', coalesce((
             select jsonb_agg(jsonb_build_object(
                      'id', l.id,
                      'descripcion', i.descripcion,
                      'unidad', i.unidad,
                      'cantidad', l.cantidad,
                      'pu_cotizado', l.pu_cotizado) order by l.id)
               from oc_items l
               join partidas p on p.id = l.partida_id
               join items i on i.id = p.item_id
              where l.obra_id = v_o.obra_id and l.numero_oc = v_o.numero), '[]'::jsonb))
    into v
    from obras ob
    join empresas e on e.id = ob.empresa_id
    join proveedores pr on pr.id = v_o.proveedor_id
   where ob.id = v_o.obra_id;
  return v;
end;
$$;

-- ============================================================ envío del proveedor (anon, por token)
-- Solo se acepta con el link vigente y la cotización "enviada"; después queda fija.
create or replace function public.enviar_cotizacion(p_token uuid, p_precios jsonb /* [{item_id, pu}] */)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_o ordenes_compra%rowtype;
  r record;
begin
  perform fn_cotizacion_limite(p_token);
  select * into v_o from ordenes_compra where token_cotizacion = p_token for update;
  if not found or v_o.estado <> 'EMITIDA' then
    raise exception 'Este link ya no está disponible';
  end if;
  if v_o.cotizacion_estado <> 'ENVIADA' then
    raise exception 'La cotización ya fue enviada';
  end if;
  if p_precios is null or jsonb_typeof(p_precios) <> 'array' then
    raise exception 'Formato de precios inválido';
  end if;
  for r in select * from jsonb_to_recordset(p_precios) x(item_id bigint, pu numeric) loop
    if r.pu is null or r.pu < 0 then
      raise exception 'Precio inválido para el ítem %', r.item_id;
    end if;
    update oc_items set pu_cotizado = r.pu
     where id = r.item_id and obra_id = v_o.obra_id and numero_oc = v_o.numero;
    if not found then
      raise exception 'El ítem % no pertenece a esta cotización', r.item_id;
    end if;
  end loop;
  if exists (select 1 from oc_items where obra_id = v_o.obra_id and numero_oc = v_o.numero and pu_cotizado is null) then
    raise exception 'Faltan precios';
  end if;
  update ordenes_compra
     set cotizacion_estado = 'RECIBIDA', cotizacion_recibida_at = now()
   where obra_id = v_o.obra_id and numero = v_o.numero;
  insert into cotizacion_accesos (token, obra_id, numero, accion, ok) values (p_token, v_o.obra_id, v_o.numero, 'ENVIAR', true);
end;
$$;

-- ============================================================ Logística
-- Al compartir el link (WhatsApp, Telegram, copiar) la cotización pasa a "enviada".
create or replace function public.marcar_cotizacion_enviada(p_obra_id bigint, p_numero text)
returns void
language plpgsql
set search_path = public, pg_temp
as $$
begin
  update ordenes_compra
     set cotizacion_estado = 'ENVIADA', cotizacion_enviada_at = now()
   where obra_id = p_obra_id and numero = p_numero
     and estado = 'EMITIDA' and cotizacion_estado = 'SIN_ENVIAR';
end;
$$;

-- Reenviar: link nuevo (el anterior deja de funcionar) y la cotización vuelve a ser editable.
create or replace function public.reenviar_cotizacion(p_obra_id bigint, p_numero text)
returns uuid
language plpgsql
set search_path = public, pg_temp
as $$
declare
  v_token uuid := gen_random_uuid();
begin
  update ordenes_compra
     set token_cotizacion = v_token, cotizacion_estado = 'ENVIADA', cotizacion_enviada_at = now(),
         cotizacion_recibida_at = null
   where obra_id = p_obra_id and numero = p_numero and estado = 'EMITIDA';
  if not found then
    raise exception 'La orden % ya no está en cotización', p_numero;
  end if;
  return v_token;
end;
$$;

revoke execute on function public.fn_cotizacion_limite(uuid) from public, anon, authenticated;
revoke execute on function public.marcar_cotizacion_enviada(bigint, text), public.reenviar_cotizacion(bigint, text) from public, anon;
grant execute on function public.marcar_cotizacion_enviada(bigint, text), public.reenviar_cotizacion(bigint, text) to authenticated, service_role;
revoke execute on function public.get_cotizacion(uuid) from public;
grant execute on function public.get_cotizacion(uuid) to anon, authenticated, service_role;

-- ============================================================ Realtime
-- La pantalla de la orden se refresca sola cuando cambian la orden o sus líneas.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    alter publication supabase_realtime add table public.ordenes_compra, public.oc_items;
  end if;
end;
$$;
