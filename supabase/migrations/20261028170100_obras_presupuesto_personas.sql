-- Gerencia crea las obras; Operaciones arma y publica el presupuesto y asigna personas; Obras pide
-- adicionales o bajas de partidas; RRHH registra personas. Las solicitudes las resuelve Gerencia.

-- ============================================================ obras y presupuesto
alter table public.obras
  add column direccion text,
  -- BORRADOR: Operaciones lo arma; PUBLICADO: solo Gerencia lo cambia (o por solicitudes aprobadas).
  -- Las obras cargadas del Excel ya tienen su presupuesto en uso; las que crea Gerencia nacen en BORRADOR.
  add column presupuesto_estado text not null default 'PUBLICADO' check (presupuesto_estado in ('BORRADOR', 'PUBLICADO')),
  add column presupuesto_publicado_at timestamptz;

create or replace function public.rol_actual()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select rol::text from public.perfiles where user_id = auth.uid()
$$;

-- ============================================================ personas (RRHH)
create table public.personas (
  id         bigint generated by default as identity primary key,
  nombre     text not null check (btrim(nombre) <> ''),
  dni        text not null unique check (dni ~ '^\d{8}$'),
  cargo      text not null check (cargo in ('RESIDENTE', 'OBRAS', 'OTRO')),
  telefono   text,
  correo     text,
  -- usuario de acceso (por ahora se vincula a mano a un usuario de prueba)
  user_id    uuid unique references auth.users (id),
  estado     text not null default 'PENDIENTE' check (estado in ('PENDIENTE', 'ACTIVA', 'BAJA')),
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);
alter table public.personas enable row level security;
create policy personas_select on public.personas for select to authenticated using (true);
revoke all on public.personas from anon;
grant select on public.personas to authenticated;
grant all on public.personas to service_role;
create trigger audit_personas after insert or update or delete on public.personas
  for each row execute function public.fn_audit();

-- ============================================================ solicitudes (Gerencia aprueba)
create table public.solicitudes (
  id            bigint generated by default as identity primary key,
  tipo          text not null check (tipo in ('ADICIONAL', 'BAJA_PARTIDA', 'PERSONA_ALTA', 'PERSONA_CAMBIO', 'PERSONA_BAJA')),
  obra_id       bigint references public.obras (id),
  partida_id    bigint references public.partidas (id) on delete set null,
  persona_id    bigint references public.personas (id),
  -- propuesta: partida adicional {etapa, requerimiento, item_id, cantidad, pu} o datos de la persona
  datos         jsonb,
  motivo        text,
  estado        text not null default 'PENDIENTE' check (estado in ('PENDIENTE', 'APROBADA', 'RECHAZADA')),
  respuesta     text,
  solicitado_by uuid not null default auth.uid() references auth.users (id),
  solicitado_at timestamptz not null default now(),
  resuelto_by   uuid references auth.users (id),
  resuelto_at   timestamptz
);
create index solicitudes_estado_idx on public.solicitudes (estado, solicitado_at desc);
create index solicitudes_obra_idx on public.solicitudes (obra_id);
alter table public.solicitudes enable row level security;
create policy solicitudes_select on public.solicitudes for select to authenticated using (true);
revoke all on public.solicitudes from anon;
grant select on public.solicitudes to authenticated;
grant all on public.solicitudes to service_role;
create trigger audit_solicitudes after insert or update or delete on public.solicitudes
  for each row execute function public.fn_audit();

