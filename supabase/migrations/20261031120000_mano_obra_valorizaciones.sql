-- El residente solo ve lo de sus obras.
drop policy if exists valorizaciones_select on public.valorizaciones;
create policy valorizaciones_select on public.valorizaciones for select to authenticated
  using (not (select public.es_residente()) or obra_id in (select public.obras_residente()));
drop policy if exists valorizacion_partidas_select on public.valorizacion_partidas;
create policy valorizacion_partidas_select on public.valorizacion_partidas for select to authenticated
  using (exists (select 1 from public.valorizaciones v where v.id = valorizacion_id));
drop policy if exists avances_select on public.avances;
create policy avances_select on public.avances for select to authenticated
  using (not (select public.es_residente()) or obra_id in (select public.obras_residente()));
drop policy if exists avance_fotos_select on public.avance_fotos;
create policy avance_fotos_select on public.avance_fotos for select to authenticated
  using (exists (select 1 from public.avances a where a.id = avance_id));

-- El residente ve las partidas de mano de obra de sus obras (cantidad, P.U. y parcial).
drop policy if exists residente_select on public.partidas;
create policy residente_select on public.partidas as restrictive for select to authenticated
  using (
    not (select public.es_residente())
    or exists (select 1 from public.oc_items i where i.partida_id = partidas.id)
    or (obra_id in (select public.obras_residente())
        and exists (select 1 from public.items it where it.id = partidas.item_id and it.rubro = 'MANO OBRA'))
  );

-- Comprometido de una partida en órdenes que no son de mano de obra valorizada ni de retención
-- (las de antes del flujo de valorizaciones, p. ej. las históricas del Excel).
create or replace function public.fn_comprometido_ordenes_mo(p_partida_id bigint)
returns numeric
language sql
stable
security definer
set search_path to 'public'
as $$
  select coalesce(sum(case when o.entrega_cerrada_at is null then l.cantidad
                           else coalesce((select sum(en.cantidad) from entregas en where en.oc_item_id = l.id), 0) end), 0)
    from oc_items l join ordenes_compra o on o.obra_id = l.obra_id and o.numero = l.numero_oc
   where l.partida_id = p_partida_id and o.estado not in ('ANULADA', 'BORRADOR')
     and o.valorizacion_id is null and not o.es_retencion;
$$;

-- El residente registra lo avanzado de una partida de mano de obra (con fotos y GPS).
create or replace function public.registrar_avance(
  p_partida_id bigint, p_cantidad numeric, p_fecha date, p_fotos text[],
  p_observacion text default null, p_lat double precision default null, p_lng double precision default null,
  p_precision double precision default null, p_capturado timestamptz default null, p_reemplaza_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_p partidas%rowtype;
  v_rubro rubro;
  v_estado_obra text;
  v_usado numeric;
  v_id bigint;
  f text;
begin
  if rol_actual() not in ('RESIDENTE', 'ADMIN') then
    raise exception 'Solo los residentes registran el avance de mano de obra';
  end if;
  select * into v_p from partidas where id = p_partida_id for update;
  if not found or v_p.dada_de_baja_at is not null then
    raise exception 'La partida no existe';
  end if;
  select rubro into v_rubro from items where id = v_p.item_id;
  if v_rubro <> 'MANO OBRA' then
    raise exception 'Solo se registra avance de partidas de mano de obra';
  end if;
  select estado into v_estado_obra from obras where id = v_p.obra_id;
  if v_estado_obra = 'CERRADA' then
    raise exception 'La obra está cerrada';
  end if;
  if rol_actual() = 'RESIDENTE' then
    if v_p.obra_id not in (select obras_residente()) then
      raise exception 'La obra no está asignada a este residente';
    end if;
    if p_lat is null or p_lng is null then
      raise exception 'Activa la ubicación del teléfono para registrar el avance';
    end if;
  end if;
  if p_cantidad is null or p_cantidad <= 0 then
    raise exception 'Ingresa la cantidad avanzada';
  end if;
  if p_fecha is null or p_fecha > (now() at time zone 'America/Lima')::date then
    raise exception 'La fecha del avance no puede ser futura';
  end if;
  if p_fotos is null or cardinality(p_fotos) = 0 then
    raise exception 'Agrega al menos una foto';
  end if;
  if p_reemplaza_id is not null and not exists (
       select 1 from avances where id = p_reemplaza_id and partida_id = p_partida_id and estado = 'OBSERVADO') then
    raise exception 'Solo se vuelve a registrar un avance observado de la misma partida';
  end if;
  select coalesce(sum(cantidad), 0) into v_usado from avances where partida_id = p_partida_id and estado <> 'OBSERVADO';
  v_usado := v_usado + fn_comprometido_ordenes_mo(p_partida_id);
  if v_usado + p_cantidad > fn_presupuesto_efectivo(p_partida_id) + 0.0001 then
    raise exception 'Solo quedan % por ejecutar en esta partida', trim_scale(greatest(fn_presupuesto_efectivo(p_partida_id) - v_usado, 0));
  end if;

  insert into avances (obra_id, partida_id, fecha, cantidad, observacion, lat, lng, precision_m, capturado_en, reemplaza_id)
  values (v_p.obra_id, p_partida_id, p_fecha, p_cantidad, nullif(btrim(coalesce(p_observacion, '')), ''),
          p_lat, p_lng, p_precision, p_capturado, p_reemplaza_id)
  returning id into v_id;
  foreach f in array p_fotos loop
    if f is null or f !~ ('^avances/' || v_p.obra_id || '/') then
      raise exception 'Ruta de foto inválida';
    end if;
    insert into avance_fotos (avance_id, path) values (v_id, f);
  end loop;
  return v_id;
end;
$$;

-- Operaciones observa un avance (no se valoriza; el residente lo vuelve a registrar si corresponde).
create or replace function public.observar_avance(p_id bigint, p_texto text)
returns void
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_a avances%rowtype;
  v_desc text;
begin
  if rol_actual() not in ('OPERACIONES', 'JEFE_OPERACIONES', 'ADMIN') then
    raise exception 'Solo Operaciones observa el avance';
  end if;
  if nullif(btrim(coalesce(p_texto, '')), '') is null then
    raise exception 'Escribe la observación';
  end if;
  select * into v_a from avances where id = p_id for update;
  if not found then
    raise exception 'El avance no existe';
  end if;
  if v_a.estado <> 'REGISTRADO' then
    raise exception 'Solo se observa un avance sin valorizar';
  end if;
  update avances set estado = 'OBSERVADO', observacion_operaciones = btrim(p_texto), observado_by = auth.uid(), observado_at = now()
   where id = p_id;
  select i.descripcion into v_desc from partidas p join items i on i.id = p.item_id where p.id = v_a.partida_id;
  insert into notificaciones (user_id, tipo, titulo, cuerpo, href)
  values (v_a.created_by, 'AVANCE', format('Avance observado: %s', v_desc), btrim(p_texto), format('/residente/mano-obra?obra=%s', v_a.obra_id));
end;
$$;

-- Valorizar: todo lo registrado sin observar de la obra pasa a una valorización (N° n).
create or replace function public.valorizar(p_obra_id bigint)
returns bigint
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_id bigint;
  v_numero integer;
  v_obra text;
  v_bruto numeric;
begin
  if rol_actual() not in ('OPERACIONES', 'JEFE_OPERACIONES', 'ADMIN') then
    raise exception 'Solo Operaciones valoriza';
  end if;
  select nombre into v_obra from obras where id = p_obra_id for update;
  if not found then
    raise exception 'La obra no existe';
  end if;
  if not exists (select 1 from avances where obra_id = p_obra_id and estado = 'REGISTRADO') then
    raise exception 'No hay avances por valorizar';
  end if;
  if exists (select 1 from avances a join partidas p on p.id = a.partida_id
              where a.obra_id = p_obra_id and a.estado = 'REGISTRADO' and p.pu is null) then
    raise exception 'Hay partidas sin P.U. en el presupuesto: Gerencia debe completarlo';
  end if;
  select coalesce(max(numero), 0) + 1 into v_numero from valorizaciones where obra_id = p_obra_id;
  insert into valorizaciones (obra_id, numero) values (p_obra_id, v_numero) returning id into v_id;
  insert into valorizacion_partidas (valorizacion_id, partida_id, cantidad, pu, porcentaje)
  select v_id, a.partida_id, sum(a.cantidad), p.pu, fn_retencion(p_obra_id, p.item_id)
    from avances a join partidas p on p.id = a.partida_id
   where a.obra_id = p_obra_id and a.estado = 'REGISTRADO'
   group by a.partida_id, p.pu, p.item_id;
  update avances set estado = 'VALORIZADO', valorizacion_id = v_id where obra_id = p_obra_id and estado = 'REGISTRADO';
  select sum(parcial) into v_bruto from valorizacion_partidas where valorizacion_id = v_id;
  perform notificar('LOGISTICA', 'VALORIZACION', format('Valorización N° %s: %s', v_numero, v_obra),
                    format('S/ %s por ordenar', to_char(v_bruto, 'FM999G999G990D00')), '/logistica/requerimientos');
  return v_id;
end;
$$;

-- Logística crea la OS de una valorización (un solo beneficiario): mismas partidas y cantidades,
-- con el P.U. neto de retención. No pasa por cotización: queda con precios confirmados.
create or replace function public.crear_orden_valorizacion(p_valorizacion_id bigint, p_numero text, p_proveedor_id bigint)
returns text
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_v valorizaciones%rowtype;
  v_numero text;
  v_obra text;
begin
  if rol_actual() not in ('LOGISTICA', 'ADMIN') then
    raise exception 'Solo Logística crea órdenes';
  end if;
  select * into v_v from valorizaciones where id = p_valorizacion_id for update;
  if not found then
    raise exception 'La valorización no existe';
  end if;
  if v_v.numero_oc is not null and exists (
       select 1 from ordenes_compra where obra_id = v_v.obra_id and numero = v_v.numero_oc and estado <> 'ANULADA') then
    raise exception 'La valorización ya tiene la OS %', v_v.numero_oc;
  end if;
  if not exists (select 1 from proveedores where id = p_proveedor_id) then
    raise exception 'Elige el proveedor';
  end if;
  v_numero := coalesce(nullif(btrim(p_numero), ''), siguiente_numero_oc(v_v.obra_id));
  if exists (select 1 from ordenes_compra where obra_id = v_v.obra_id and numero = v_numero) then
    raise exception 'Ya existe la orden % en esta obra', v_numero;
  end if;
  select nombre into v_obra from obras where id = v_v.obra_id;
  insert into ordenes_compra (obra_id, numero, tipo, proveedor_id, fecha, estado, valorizacion_id, glosa_rhe)
  values (v_v.obra_id, v_numero, 'OS', p_proveedor_id, current_date, 'EMITIDA', v_v.id,
          upper(format('SERVICIO DE VALORIZACIÓN N° %s %s', v_v.numero, v_obra)));
  insert into oc_items (obra_id, numero_oc, partida_id, cantidad, pu_cotizado)
  select v_v.obra_id, v_numero, vp.partida_id, vp.cantidad, round((vp.parcial - vp.retencion) / vp.cantidad, 4)
    from valorizacion_partidas vp where vp.valorizacion_id = v_v.id
   order by vp.partida_id;
  update valorizaciones set numero_oc = v_numero where id = v_v.id;
  perform confirmar_precios(v_v.obra_id, v_numero);
  return v_numero;
end;
$$;

-- Retención acumulada de una obra que aún no tiene OS de retención (no anulada).
create or replace view public.v_retencion_obra with (security_invoker = true) as
select v.obra_id,
       sum(vp.retencion) as retencion,
       (select o.numero from ordenes_compra o where o.obra_id = v.obra_id and o.es_retencion and o.estado <> 'ANULADA' limit 1) as numero_oc
  from valorizaciones v
  join valorizacion_partidas vp on vp.valorizacion_id = v.id
  -- Solo valorizaciones con su OS pagada: lo retenido es de trabajos ya pagados.
  join ordenes_compra o on o.obra_id = v.obra_id and o.numero = v.numero_oc and o.estado in ('PAGADA', 'EN_ENTREGA', 'RECIBIDA')
 group by v.obra_id;

-- Logística crea la OS de retención al cerrar la obra: una línea por partida con lo retenido.
create or replace function public.crear_orden_retencion(p_obra_id bigint, p_numero text, p_proveedor_id bigint)
returns text
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_numero text;
  v_obra text;
  v_estado text;
begin
  if rol_actual() not in ('LOGISTICA', 'ADMIN') then
    raise exception 'Solo Logística crea órdenes';
  end if;
  select nombre, estado into v_obra, v_estado from obras where id = p_obra_id for update;
  if v_estado <> 'CERRADA' then
    raise exception 'La retención se paga al cerrar la obra';
  end if;
  if exists (select 1 from ordenes_compra where obra_id = p_obra_id and es_retencion and estado <> 'ANULADA') then
    raise exception 'La obra ya tiene su OS de retención';
  end if;
  if exists (select 1 from valorizaciones v
              where v.obra_id = p_obra_id
                and not exists (select 1 from ordenes_compra o where o.obra_id = v.obra_id and o.numero = v.numero_oc
                                   and o.estado in ('PAGADA', 'EN_ENTREGA', 'RECIBIDA'))) then
    raise exception 'Hay valorizaciones sin pagar: la retención se paga al final';
  end if;
  if not exists (select 1 from proveedores where id = p_proveedor_id) then
    raise exception 'Elige el proveedor';
  end if;
  v_numero := coalesce(nullif(btrim(p_numero), ''), siguiente_numero_oc(p_obra_id));
  if exists (select 1 from ordenes_compra where obra_id = p_obra_id and numero = v_numero) then
    raise exception 'Ya existe la orden % en esta obra', v_numero;
  end if;
  insert into ordenes_compra (obra_id, numero, tipo, proveedor_id, fecha, estado, es_retencion, glosa_rhe)
  values (p_obra_id, v_numero, 'OS', p_proveedor_id, current_date, 'EMITIDA', true, upper(format('DEVOLUCIÓN DE RETENCIÓN %s', v_obra)));
  insert into oc_items (obra_id, numero_oc, partida_id, cantidad, pu_cotizado)
  select p_obra_id, v_numero, vp.partida_id, sum(vp.cantidad), round(sum(vp.retencion) / sum(vp.cantidad), 4)
    from valorizaciones v join valorizacion_partidas vp on vp.valorizacion_id = v.id
   where v.obra_id = p_obra_id
   group by vp.partida_id
  having sum(vp.retencion) > 0
   order by vp.partida_id;
  if not found then
    raise exception 'La obra no tiene retención por pagar';
  end if;
  perform confirmar_precios(p_obra_id, v_numero);
  return v_numero;
end;
$$;

