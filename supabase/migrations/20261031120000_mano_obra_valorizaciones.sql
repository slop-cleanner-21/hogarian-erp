-- Mano de obra: el residente registra el avance diario con fotos; Operaciones lo revisa (observa lo
-- que está mal) y valoriza a una fecha de corte descontando la retención de cada ítem; Logística
-- crea una OS por valorización con el P.U. neto. La retención acumulada se paga en una última OS
-- al cerrar la obra.

-- obras.estado ya existe (EN_EJECUCION por defecto); al cerrar la obra pasa a CERRADA.
alter table public.obras add column if not exists cerrada_at timestamptz;
alter table public.obras add column if not exists cerrada_by uuid;

create table if not exists public.valorizaciones (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id),
  numero integer not null,
  fecha_corte timestamptz not null default now(),
  numero_oc text,
  created_by uuid not null default auth.uid(),
  created_at timestamptz not null default now(),
  unique (obra_id, numero)
);

-- Foto de cada valorización por partida: cantidad, P.U. y % de retención al momento de valorizar.
create table if not exists public.valorizacion_partidas (
  valorizacion_id bigint not null references public.valorizaciones (id) on delete cascade,
  partida_id bigint not null references public.partidas (id),
  cantidad numeric(14, 4) not null check (cantidad > 0),
  pu numeric(12, 4) not null,
  porcentaje numeric(5, 2) not null,
  parcial numeric(14, 2) generated always as (round(cantidad * pu, 2)) stored,
  retencion numeric(14, 2) generated always as (round(round(cantidad * pu, 2) * porcentaje / 100, 2)) stored,
  primary key (valorizacion_id, partida_id)
);

create table if not exists public.avances (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id),
  partida_id bigint not null references public.partidas (id),
  fecha date not null default (now() at time zone 'America/Lima')::date,
  cantidad numeric(14, 4) not null check (cantidad > 0),
  observacion text,
  estado text not null default 'REGISTRADO' check (estado in ('REGISTRADO', 'OBSERVADO', 'VALORIZADO')),
  observacion_operaciones text,
  observado_by uuid,
  observado_at timestamptz,
  valorizacion_id bigint references public.valorizaciones (id),
  reemplaza_id bigint references public.avances (id),
  lat double precision,
  lng double precision,
  precision_m double precision,
  capturado_en timestamptz,
  created_by uuid not null default auth.uid(),
  created_at timestamptz not null default now()
);
create index if not exists avances_obra_estado on public.avances (obra_id, estado);
create index if not exists avances_partida on public.avances (partida_id);

create table if not exists public.avance_fotos (
  id bigint generated by default as identity primary key,
  avance_id bigint not null references public.avances (id) on delete cascade,
  path text not null
);

alter table public.ordenes_compra add column if not exists valorizacion_id bigint references public.valorizaciones (id);
alter table public.ordenes_compra add column if not exists es_retencion boolean not null default false;

