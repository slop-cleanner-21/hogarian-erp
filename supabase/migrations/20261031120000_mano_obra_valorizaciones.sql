-- Seguimiento: las OS de valorización y de retención no van por entregas; la mano de obra
-- se sigue con sus avances (sin valorizar, valorizado sin pagar, pagado) y su retención.

create or replace view public.v_seguimiento_partida with (security_invoker = true) as
 WITH lineas AS (
         SELECT l.partida_id,
            l.cantidad,
            o.estado,
            o.entrega_cerrada_at,
            COALESCE(( SELECT sum(en.cantidad) AS sum
                   FROM entregas en
                  WHERE (en.oc_item_id = l.id)), (0)::numeric) AS entregado
           FROM (oc_items l
             JOIN ordenes_compra o ON (((o.obra_id = l.obra_id) AND (o.numero = l.numero_oc))))
          WHERE ((o.estado <> ALL (ARRAY['ANULADA'::estado_oc, 'BORRADOR'::estado_oc])) AND (o.valorizacion_id IS NULL) AND (NOT o.es_retencion))
        ), x AS (
         SELECT lineas.partida_id,
            sum(
                CASE
                    WHEN (lineas.estado = ANY (ARRAY['EMITIDA'::estado_oc, 'PRECIOS_CONFIRMADOS'::estado_oc, 'FACTURADA'::estado_oc])) THEN lineas.cantidad
                    ELSE (0)::numeric
                END) AS en_logistica,
            sum(
                CASE
                    WHEN (lineas.estado = 'EN_TESORERIA'::estado_oc) THEN lineas.cantidad
                    ELSE (0)::numeric
                END) AS en_tesoreria,
            sum(
                CASE
                    WHEN ((lineas.estado = ANY (ARRAY['PAGADA'::estado_oc, 'EN_ENTREGA'::estado_oc, 'RECIBIDA'::estado_oc])) AND (lineas.entrega_cerrada_at IS NULL)) THEN GREATEST((lineas.cantidad - lineas.entregado), (0)::numeric)
                    ELSE (0)::numeric
                END) AS por_recibir,
            sum(lineas.entregado) AS recibido
           FROM lineas
          GROUP BY lineas.partida_id
        )
 SELECT p.id AS partida_id,
    p.obra_id,
    p.etapa,
    p.requerimiento,
    p.item_id,
    i.descripcion,
    i.unidad,
    i.rubro,
        CASE
            WHEN (i.rubro = 'MATERIAL'::rubro) THEN 'MATERIALES'::text
            WHEN (i.rubro = 'MANO OBRA'::rubro) THEN 'MANO_OBRA'::text
            ELSE 'SUBCONTRATOS'::text
        END AS grupo,
    p.cantidad AS presupuestado,
    p.pu,
    COALESCE(x.en_logistica, (0)::numeric) AS en_logistica,
    COALESCE(x.en_tesoreria, (0)::numeric) AS en_tesoreria,
    COALESCE(x.por_recibir, (0)::numeric) AS por_recibir,
    COALESCE(x.recibido, (0)::numeric) AS recibido,
    GREATEST(((((ef.efectivo - COALESCE(x.en_logistica, (0)::numeric)) - COALESCE(x.en_tesoreria, (0)::numeric)) - COALESCE(x.por_recibir, (0)::numeric)) - COALESCE(x.recibido, (0)::numeric)), (0)::numeric) AS por_pedir,
    ef.efectivo AS presupuesto_efectivo,
    ef.recibido AS adelanto_recibido,
    ef.dado AS adelanto_dado,
    COALESCE(( SELECT sum(ri.cantidad) AS sum
           FROM (requerimientos_obra_items ri
             JOIN requerimientos_obra rq ON ((rq.id = ri.requerimiento_id)))
          WHERE ((ri.partida_id = p.id) AND (rq.estado = 'VIGENTE'::text))), (0)::numeric) AS requerido,
    fn_orden_etapa(p.obra_id, p.etapa) AS orden_etapa,
    COALESCE(( SELECT sum(a.cantidad) AS sum
           FROM avances a
          WHERE ((a.partida_id = p.id) AND (a.estado = 'REGISTRADO'::text))), (0)::numeric) AS ejecutado_sin_valorizar,
    COALESCE(( SELECT sum(vp.cantidad) AS sum
           FROM ((valorizacion_partidas vp
             JOIN valorizaciones v ON ((v.id = vp.valorizacion_id)))
             LEFT JOIN ordenes_compra o ON (((o.obra_id = v.obra_id) AND (o.numero = v.numero_oc))))
          WHERE ((vp.partida_id = p.id) AND ((o.estado IS NULL) OR (o.estado <> ALL (ARRAY['PAGADA'::estado_oc, 'EN_ENTREGA'::estado_oc, 'RECIBIDA'::estado_oc]))))), (0)::numeric) AS valorizado_sin_pagar,
    COALESCE(( SELECT sum(vp.cantidad) AS sum
           FROM ((valorizacion_partidas vp
             JOIN valorizaciones v ON ((v.id = vp.valorizacion_id)))
             JOIN ordenes_compra o ON (((o.obra_id = v.obra_id) AND (o.numero = v.numero_oc))))
          WHERE ((vp.partida_id = p.id) AND (o.estado = ANY (ARRAY['PAGADA'::estado_oc, 'EN_ENTREGA'::estado_oc, 'RECIBIDA'::estado_oc])))), (0)::numeric) AS valorizado_pagado,
    COALESCE(( SELECT sum(vp.retencion) AS sum
           FROM valorizacion_partidas vp
          WHERE (vp.partida_id = p.id)), (0)::numeric) AS retencion_acumulada
   FROM (((partidas p
     JOIN items i ON ((i.id = p.item_id)))
     JOIN v_presupuesto_efectivo ef ON ((ef.partida_id = p.id)))
     LEFT JOIN x ON ((x.partida_id = p.id)))
  WHERE (p.dada_de_baja_at IS NULL);

-- La OS de retención suma en montos, no en cantidades compradas.

create or replace view public.v_avance_partida with (security_invoker = true) as
 SELECT p.id AS partida_id,
    p.obra_id,
    p.etapa,
    p.requerimiento,
    p.item_id,
    i.descripcion,
    i.unidad,
    i.rubro,
    p.cantidad AS presupuestado,
    p.pu,
    round((p.cantidad * p.pu), 2) AS parcial,
    COALESCE(c.comprado, (0)::numeric) AS comprado,
    COALESCE(c.monto_comprado, (0)::numeric) AS monto_comprado,
    COALESCE(e.llegado, (0)::numeric) AS llegado,
    COALESCE(e.fotos, (0)::bigint) AS fotos
   FROM (((partidas p
     JOIN items i ON ((i.id = p.item_id)))
     LEFT JOIN LATERAL ( SELECT sum(
                CASE
                    WHEN oc.es_retencion THEN (0)::numeric
                    WHEN (oc.entrega_cerrada_at IS NULL) THEN l.cantidad
                    ELSE COALESCE(( SELECT sum(en.cantidad) AS sum
                       FROM entregas en
                      WHERE (en.oc_item_id = l.id)), (0)::numeric)
                END) AS comprado,
            sum(
                CASE
                    WHEN (oc.entrega_cerrada_at IS NULL) THEN COALESCE(l.parcial, (0)::numeric)
                    ELSE round((COALESCE(( SELECT sum(en.cantidad) AS sum
                       FROM entregas en
                      WHERE (en.oc_item_id = l.id)), (0)::numeric) * COALESCE(l.pu_efectivo, (0)::numeric)), 2)
                END) AS monto_comprado
           FROM (v_oc_items_calc l
             JOIN ordenes_compra oc ON (((oc.obra_id = l.obra_id) AND (oc.numero = l.numero_oc))))
          WHERE ((l.partida_id = p.id) AND (l.estado <> 'ANULADA'::estado_oc))) c ON (true))
     LEFT JOIN LATERAL ( SELECT sum(en.cantidad) AS llegado,
            ( SELECT count(*) AS count
                   FROM ((entrega_fotos f
                     JOIN entregas e2 ON ((e2.id = f.entrega_id)))
                     JOIN oc_items l2 ON ((l2.id = e2.oc_item_id)))
                  WHERE (l2.partida_id = p.id)) AS fotos
           FROM (entregas en
             JOIN oc_items l ON ((l.id = en.oc_item_id)))
          WHERE (l.partida_id = p.id)) e ON (true))
  WHERE (p.dada_de_baja_at IS NULL);

create or replace view public.v_partidas with (security_invoker = true) as
 SELECT p.id,
    p.codigo,
    p.obra_id,
    ob.nombre AS obra,
    ob.empresa_id,
    p.etapa,
    p.requerimiento,
    p.item_id,
    i.descripcion,
    i.unidad,
    i.rubro,
    p.cantidad,
    p.pu,
    round((p.cantidad * p.pu), 2) AS parcial,
    round(fn_pu_max(p.pu, i.tolerancia_pct), 4) AS pu_max,
    COALESCE(x.cant, (0)::numeric) AS cant_comprometida,
    COALESCE(x.monto, (0)::numeric) AS monto_ejecutado,
    (ef.efectivo - COALESCE(x.cant, (0)::numeric)) AS saldo_cant,
    (COALESCE(round((ef.efectivo * p.pu), 2), (0)::numeric) - COALESCE(x.monto, (0)::numeric)) AS saldo_monto,
        CASE
            WHEN (ef.efectivo > (0)::numeric) THEN round((COALESCE(x.cant, (0)::numeric) / ef.efectivo), 4)
            ELSE NULL::numeric
        END AS avance,
    i.tipo_material,
    ef.efectivo AS cantidad_efectiva,
    ef.recibido AS adelanto_recibido,
    ef.dado AS adelanto_dado
   FROM ((((partidas p
     JOIN v_presupuesto_efectivo ef ON ((ef.partida_id = p.id)))
     JOIN obras ob ON ((ob.id = p.obra_id)))
     JOIN items i ON ((i.id = p.item_id)))
     LEFT JOIN LATERAL ( SELECT sum(
                CASE
                    WHEN oc.es_retencion THEN (0)::numeric
                    WHEN (oc.entrega_cerrada_at IS NULL) THEN c.cantidad
                    ELSE COALESCE(( SELECT sum(en.cantidad) AS sum
                       FROM entregas en
                      WHERE (en.oc_item_id = c.id)), (0)::numeric)
                END) AS cant,
            sum(
                CASE
                    WHEN (oc.entrega_cerrada_at IS NULL) THEN COALESCE(c.parcial, (0)::numeric)
                    ELSE round((COALESCE(( SELECT sum(en.cantidad) AS sum
                       FROM entregas en
                      WHERE (en.oc_item_id = c.id)), (0)::numeric) * COALESCE(c.pu_efectivo, (0)::numeric)), 2)
                END) AS monto
           FROM (v_oc_items_calc c
             JOIN ordenes_compra oc ON (((oc.obra_id = c.obra_id) AND (oc.numero = c.numero_oc))))
          WHERE ((c.partida_id = p.id) AND (c.estado <> ALL (ARRAY['ANULADA'::estado_oc, 'BORRADOR'::estado_oc])))) x ON (true))
  WHERE (p.dada_de_baja_at IS NULL);

CREATE OR REPLACE FUNCTION public.fn_comprometido_partida(p_partida_id bigint)
 RETURNS numeric
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select coalesce(sum(case when o.entrega_cerrada_at is null then l.cantidad
                           else coalesce((select sum(en.cantidad) from entregas en where en.oc_item_id = l.id), 0) end), 0)
    from oc_items l join ordenes_compra o on o.obra_id = l.obra_id and o.numero = l.numero_oc
   where l.partida_id = p_partida_id and o.estado not in ('ANULADA', 'BORRADOR') and not o.es_retencion;
$function$;

-- La mano de obra ya no se ordena directo: sale de una valorización.

CREATE OR REPLACE FUNCTION public.crear_orden(p_obra_id bigint, p_numero text, p_proveedor_id bigint, p_tipo tipo_orden, p_items jsonb)
 RETURNS text
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
declare
  v_numero text;
  v_p record;
  r record;
  v_comp numeric;
begin
  if not exists (select 1 from obras where id = p_obra_id) then
    raise exception 'La obra % no existe', p_obra_id;
  end if;
  if not exists (select 1 from proveedores where id = p_proveedor_id) then
    raise exception 'El proveedor % no existe', p_proveedor_id;
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'La orden debe tener al menos un ítem';
  end if;
  if exists (select 1 from jsonb_to_recordset(p_items) x(partida_id bigint, cantidad numeric)
              where x.partida_id is null or x.cantidad is null or x.cantidad <= 0) then
    raise exception 'Cada ítem requiere partida_id y una cantidad mayor que cero';
  end if;

  if exists (select 1 from jsonb_to_recordset(p_items) x(partida_id bigint)
              join partidas p on p.id = x.partida_id join items i on i.id = p.item_id
             where i.rubro = 'MANO OBRA') then
    raise exception 'La mano de obra se ordena desde una valorización de Operaciones';
  end if;
  if (select estado from obras where id = p_obra_id) = 'CERRADA' then
    raise exception 'La obra está cerrada';
  end if;

  v_numero := nullif(btrim(p_numero), '');
  if v_numero is null then
    v_numero := siguiente_numero_oc(p_obra_id);
  end if;
  if exists (select 1 from ordenes_compra where obra_id = p_obra_id and numero = v_numero) then
    raise exception 'Ya existe la orden % en esta obra', v_numero;
  end if;

  -- valida saldo de cada partida (bloqueadas en orden de id para evitar deadlocks)
  for r in
    select x.partida_id, sum(x.cantidad) as cantidad
      from jsonb_to_recordset(p_items) x(partida_id bigint, cantidad numeric)
     group by x.partida_id
     order by x.partida_id
  loop
    select p.obra_id, fn_presupuesto_efectivo(p.id) as cantidad, p.codigo into v_p
      from partidas p where p.id = r.partida_id for update;
    if not found then
      raise exception 'La partida % no existe', r.partida_id;
    end if;
    if v_p.obra_id <> p_obra_id then
      raise exception 'La partida % no pertenece a la obra de la orden', v_p.codigo;
    end if;
    -- Si la entrega de una orden se cerró incompleta, lo que no llegó vuelve al saldo.
    select coalesce(sum(case when o.entrega_cerrada_at is null then l.cantidad
                             else coalesce((select sum(en.cantidad) from entregas en where en.oc_item_id = l.id), 0) end), 0) into v_comp
      from oc_items l
      join ordenes_compra o on o.obra_id = l.obra_id and o.numero = l.numero_oc
     where l.partida_id = r.partida_id
       and o.estado not in ('ANULADA', 'BORRADOR')
       and not o.es_retencion;
    if r.cantidad > v_p.cantidad - v_comp then
      raise exception 'La cantidad solicitada (%) de la partida % excede su saldo disponible (%)',
        trim_scale(r.cantidad), v_p.codigo, trim_scale(v_p.cantidad - v_comp);
    end if;
  end loop;

  insert into ordenes_compra (obra_id, numero, tipo, proveedor_id, fecha, estado)
  values (p_obra_id, v_numero, coalesce(p_tipo, 'OC'), p_proveedor_id, current_date, 'EMITIDA');

  -- En la OS el precio de partida es el del presupuesto: Logística solo confirma lo que no cambie.
  insert into oc_items (obra_id, numero_oc, partida_id, cantidad, pu_cotizado)
  select p_obra_id, v_numero, x.partida_id, x.cantidad, case when coalesce(p_tipo, 'OC') = 'OS' then p.pu end
    from rows from (jsonb_to_recordset(p_items) as (partida_id bigint, cantidad numeric))
         with ordinality as x(partida_id, cantidad, n)
    join partidas p on p.id = x.partida_id
   order by x.n;

  return v_numero;
exception
  when unique_violation then
    raise exception 'Ya existe la orden % en esta obra', v_numero;
end;
$function$;

CREATE OR REPLACE FUNCTION public.guardar_partidas(p_obra_id bigint, p_partidas jsonb, p_eliminar bigint[])
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_rol text := rol_actual();
  v_estado text;
  r record;
  v_comprado numeric;
  v_n integer := 0;
begin
  select presupuesto_estado into v_estado from obras where id = p_obra_id for update;
  if not found then
    raise exception 'La obra no existe';
  end if;
  if v_rol not in ('GERENCIA', 'ADMIN') then
    raise exception 'Solo Gerencia carga y modifica el presupuesto';
  end if;

  -- Bajas: solo partidas sin órdenes.
  if p_eliminar is not null and cardinality(p_eliminar) > 0 then
    if exists (select 1 from oc_items where partida_id = any (p_eliminar)) then
      raise exception 'No se puede quitar una partida que ya tiene órdenes';
    end if;
    if exists (select 1 from requerimientos_obra_items where partida_id = any (p_eliminar))
       or exists (select 1 from adelantos where partida_origen_id = any (p_eliminar) or partida_destino_id = any (p_eliminar)) then
      raise exception 'No se puede quitar una partida que ya tiene requerimientos o adelantos';
    end if;
    delete from partidas where obra_id = p_obra_id and id = any (p_eliminar);
    get diagnostics v_n = row_count;
  end if;

  for r in select * from jsonb_to_recordset(coalesce(p_partidas, '[]'::jsonb))
                        x(id bigint, etapa text, requerimiento text, item_id bigint, cantidad numeric, pu numeric) loop
    if r.etapa is null or r.item_id is null or r.cantidad is null or r.cantidad < 0 or (r.pu is not null and r.pu < 0) then
      raise exception 'Cada partida necesita etapa, ítem, cantidad y P.U. válidos';
    end if;
    if r.id is null then
      insert into partidas (obra_id, etapa, requerimiento, item_id, cantidad, pu)
      values (p_obra_id, r.etapa, coalesce(r.requerimiento, 'REGULAR'), r.item_id, r.cantidad, r.pu);
    else
      select coalesce(sum(l.cantidad), 0) into v_comprado
        from v_oc_items_calc l join ordenes_compra o on o.obra_id = l.obra_id and o.numero = l.numero_oc
       where l.partida_id = r.id and l.estado <> 'ANULADA' and not o.es_retencion;
      -- En mano de obra cuenta también lo avanzado que aún no tiene OS.
      v_comprado := v_comprado + coalesce((select sum(cantidad) from avances where partida_id = r.id and estado = 'REGISTRADO'), 0)
                  + coalesce((select sum(vp.cantidad) from valorizacion_partidas vp join valorizaciones v on v.id = vp.valorizacion_id
                               where vp.partida_id = r.id
                                 and not exists (select 1 from ordenes_compra o where o.obra_id = v.obra_id and o.numero = v.numero_oc and o.estado <> 'ANULADA')), 0);
      -- Con adelantos, lo que cuenta es el presupuesto efectivo (cantidad + recibido - dado).
      if r.cantidad + fn_presupuesto_efectivo(r.id) - (select cantidad from partidas where id = r.id) < v_comprado - 0.0001 then
        raise exception 'La cantidad de una partida no puede quedar debajo de lo ya comprado (%), contando sus adelantos', v_comprado;
      end if;
      update partidas set etapa = r.etapa, requerimiento = coalesce(r.requerimiento, 'REGULAR'), item_id = r.item_id,
                          cantidad = r.cantidad, pu = r.pu
       where id = r.id and obra_id = p_obra_id;
    end if;
    v_n := v_n + 1;
  end loop;
  return v_n;
end;
$function$;

-- OS de valorización o de retención: su ejecución ya está registrada; al enviar la constancia
-- queda recibida. La de retención no lleva contrato (libera lo de contratos ya firmados).

CREATE OR REPLACE FUNCTION public.enviar_constancia(p_obra_id bigint, p_numero text)
 RETURNS void
 LANGUAGE plpgsql
 SET search_path TO 'public', 'pg_temp'
AS $function$
begin
  update ordenes_compra
     set estado = case when valorizacion_id is not null or es_retencion then 'RECIBIDA'::estado_oc else 'EN_ENTREGA'::estado_oc end
   where obra_id = p_obra_id and numero = p_numero and estado = 'PAGADA';
  if not found then
    raise exception 'La orden % no está pagada', p_numero;
  end if;
end;
$function$;

CREATE OR REPLACE FUNCTION public.enviar_a_tesoreria(p_obra_id bigint, p_numero text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_o ordenes_compra%rowtype;
  v_sobre int;
  v_bajo int;
begin
  if coalesce((select rol::text from perfiles where user_id = auth.uid()), '') not in ('LOGISTICA', 'ADMIN') then
    raise exception 'Solo Logística envía órdenes a Tesorería';
  end if;
  select * into v_o from ordenes_compra where obra_id = p_obra_id and numero = p_numero for update;
  if not found then
    raise exception 'La orden % no existe', p_numero;
  end if;
  if v_o.estado <> 'FACTURADA' then
    raise exception 'La orden % no está lista para enviar (estado %): todas sus líneas deben tener comprobante', p_numero, v_o.estado;
  end if;
  if v_o.tipo = 'OS' and not v_o.es_retencion and not exists (
       select 1 from adjuntos where tipo = 'CONTRATO' and obra_id = p_obra_id and numero_oc = p_numero) then
    raise exception 'Falta el contrato firmado de la OS %', p_numero;
  end if;
  update ordenes_compra set estado = 'EN_TESORERIA' where obra_id = p_obra_id and numero = p_numero;

  if v_o.tipo = 'OS' then
    select count(*) filter (where pu_efectivo > pu_partida + 0.0001), count(*) filter (where pu_efectivo < pu_partida - 0.0001)
      into v_sobre, v_bajo
      from v_oc_items_calc where obra_id = p_obra_id and numero_oc = p_numero;
    if v_sobre + v_bajo > 0 then
      perform notificar('TESORERIA', 'OS_PRECIO',
        format('OS %s con precios distintos al presupuesto', p_numero),
        concat_ws(', ',
          case when v_sobre > 0 then format('%s sobre el presupuesto', v_sobre) end,
          case when v_bajo > 0 then format('%s por debajo (ahorro)', v_bajo) end),
        format('/tesoreria/pago/%s/%s', p_obra_id, p_numero));
    end if;
  end if;
end;
$function$;
