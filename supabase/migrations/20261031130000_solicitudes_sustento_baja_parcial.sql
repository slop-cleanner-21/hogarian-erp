-- Adicionales: Operaciones los pide de los 3 presupuestos (materiales, mano de obra y
-- subcontratos) con archivos de sustento. Bajas: además de toda la partida, se puede dar de baja
-- solo lo que falta (lo que no está comprometido, requerido ni avanzado).

create table if not exists public.solicitud_adjuntos (
  id bigint generated by default as identity primary key,
  solicitud_id bigint not null references public.solicitudes (id) on delete cascade,
  path text not null,
  nombre text not null,
  mime text,
  created_by uuid not null default auth.uid(),
  created_at timestamptz not null default now()
);
alter table public.solicitud_adjuntos enable row level security;
revoke all on public.solicitud_adjuntos from anon, authenticated;
grant select on public.solicitud_adjuntos to authenticated;
drop policy if exists solicitud_adjuntos_select on public.solicitud_adjuntos;
create policy solicitud_adjuntos_select on public.solicitud_adjuntos for select to authenticated
  using (not (select public.es_residente()));

-- Lo que falta de una partida: lo que se puede dar de baja sin tocar lo comprometido, lo requerido
-- por Operaciones ni lo avanzado de mano de obra (aunque aún no tenga OS). Nunca más que su cantidad.
create or replace function public.fn_faltante_partida(p_partida_id bigint)
returns numeric
language sql
stable
security definer
set search_path to 'public'
as $$
  select greatest(least(p.cantidad,
           fn_presupuesto_efectivo(p.id) - greatest(
             fn_comprometido_partida(p.id)
               + coalesce((select sum(a.cantidad) from avances a where a.partida_id = p.id and a.estado = 'REGISTRADO'), 0)
               + coalesce((select sum(vp.cantidad) from valorizacion_partidas vp join valorizaciones v on v.id = vp.valorizacion_id
                            where vp.partida_id = p.id
                              and not exists (select 1 from ordenes_compra o where o.obra_id = v.obra_id and o.numero = v.numero_oc and o.estado <> 'ANULADA')), 0),
             coalesce((select sum(ri.cantidad) from requerimientos_obra_items ri join requerimientos_obra rq on rq.id = ri.requerimiento_id
                        where ri.partida_id = p.id and rq.estado = 'VIGENTE'), 0))), 0)
    from partidas p where p.id = p_partida_id;
$$;
grant execute on function public.fn_faltante_partida(bigint) to authenticated;

-- Archivos de sustento de un adicional o una baja (fotos o PDF ya subidos a documentos/solicitudes/{id}/).
create or replace function public.adjuntar_solicitud(p_solicitud_id bigint, p_archivos jsonb)
returns integer
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  s solicitudes%rowtype;
  r record;
  v_n integer := 0;
begin
  if rol_actual() not in ('OPERACIONES', 'JEFE_OPERACIONES', 'ADMIN') then
    raise exception 'Solo Operaciones adjunta sustento';
  end if;
  select * into s from solicitudes where id = p_solicitud_id;
  if not found or s.tipo not in ('ADICIONAL', 'BAJA_PARTIDA') then
    raise exception 'La solicitud no existe';
  end if;
  if s.estado not in ('POR_JEFE', 'PENDIENTE') then
    raise exception 'La solicitud ya fue resuelta';
  end if;
  if rol_actual() = 'OPERACIONES' and s.solicitado_by <> auth.uid() then
    raise exception 'Solo quien pidió la solicitud adjunta su sustento';
  end if;
  for r in select * from jsonb_to_recordset(coalesce(p_archivos, '[]'::jsonb)) x(path text, nombre text, mime text) loop
    if r.path is null or r.path !~ ('^solicitudes/' || p_solicitud_id || '/') or r.path ~* '\.svg$' or coalesce(r.mime, '') ilike '%svg%' then
      raise exception 'Archivo inválido';
    end if;
    insert into solicitud_adjuntos (solicitud_id, path, nombre, mime) values (p_solicitud_id, r.path, coalesce(nullif(btrim(r.nombre), ''), 'archivo'), r.mime);
    v_n := v_n + 1;
  end loop;
  return v_n;
end;
$$;
revoke execute on function public.adjuntar_solicitud(bigint, jsonb) from public, anon;
grant execute on function public.adjuntar_solicitud(bigint, jsonb) to authenticated;

